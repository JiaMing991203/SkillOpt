PRELUDE = r"""-- GENERATED by research/officeqa/oqa_fw_lean.py. Rule OQA-FW-1.
-- Do not edit: regenerate it. The generator records this file's digest beside the compiler's output.
namespace OqaFramework

/-- A three-valued (Kleene) value. `uu` is UNKNOWN: the records do not settle it. It is a value, not
    an absence, and it is never the same as false. -/
inductive KV where
  | tt : KV
  | ff : KV
  | uu : KV
deriving DecidableEq, Repr

def kand : KV → KV → KV
  | KV.ff, _ => KV.ff
  | _, KV.ff => KV.ff
  | KV.uu, _ => KV.uu
  | _, KV.uu => KV.uu
  | KV.tt, KV.tt => KV.tt

def kor : KV → KV → KV
  | KV.tt, _ => KV.tt
  | _, KV.tt => KV.tt
  | KV.uu, _ => KV.uu
  | _, KV.uu => KV.uu
  | KV.ff, KV.ff => KV.ff

/-- A clause is read disjunctively, a conjunctive normal form conjunctively. An EMPTY conjunctive
    normal form is true and an empty clause is false, which are the identities of the two folds. -/
def evalClause (c : List KV) : KV := c.foldl kor KV.ff
def evalCNF (cs : List (List KV)) : KV := cs.foldl (fun a c => kand a (evalClause c)) KV.tt

/-- The class of one subject of a `concludes` rule. `counterConverse` exists only for a rule stated as
    a biconditional: a consequence holding where the conditions do not refutes "exactly when" and does
    not refute "whenever". -/
inductive Cls where
  | support : Cls
  | counter : Cls
  | counterConverse : Cls
  | consistent : Cls
  | neutral : Cls
  | undetermined : Cls
deriving DecidableEq, Repr

def classify (isIff : Bool) (cond cons : KV) : Cls :=
  match cond, cons with
  | KV.uu, _ => Cls.undetermined
  | _, KV.uu => Cls.undetermined
  | KV.tt, KV.tt => Cls.support
  | KV.tt, KV.ff => Cls.counter
  | KV.ff, KV.tt => if isIff then Cls.counterConverse else Cls.neutral
  | KV.ff, KV.ff => Cls.consistent

/-- One scored subject, as its LITERAL VALUES rather than as a verdict: the conditions as a
    conjunctive normal form of Kleene values, and the consequence's Kleene value. -/
structure Row where
  isIff : Bool
  cond : List (List KV)
  cons : KV
deriving Repr

def rowClass (r : Row) : Cls := classify r.isIff (evalCNF r.cond) r.cons
def countCls (k : Cls) (xs : List Cls) : Nat := (xs.filter (fun x => decide (x = k))).length

/-- The obligation states of the slice. -/
inductive OS where
  | discharged : OS
  | outstanding : OS
  | unknown : OS
  | notRequired : OS
deriving DecidableEq, Repr

/-- `column_identified`: discharged only when the learned licence is TRUE. -/
def colIdentified : KV → OS
  | KV.tt => OS.discharged
  | _ => OS.unknown

/-- `unit_resolved`: the applicable money scale is identified. -/
def unitResolved : KV → OS
  | KV.tt => OS.discharged
  | KV.uu => OS.unknown
  | KV.ff => OS.notRequired

/-- `conversion_accounted`, as the 2026-11-22 audit left it. CORRECTED 2026-11-23 under
    `oqa.fw.lean.v2`: the first version of this definition took only three inputs and encoded the rule
    BEFORE that audit, so it could not reproduce the states the checker records, and the compiler said
    so - 24 `decide` goals were disproved the first time this file was ever compiled. The two inputs it
    was missing are the two the audit added.

    The order of the tests is the rule:
    * a question that asks for no money scale requires no conversion of anything;
    * a number that is not an operand or result of a WRITTEN CALCULATION requires no conversion. Without
      this the obligation was raised for every number the actor typed, including ones it was only
      reading aloud: 70 of one attempt's 227 written numbers were accused that way and none survived
      the audit;
    * an unresolved scale leaves it UNKNOWN, so an unresolved scale can never be reported as a missing
      conversion;
    * no factor defined between the two scales leaves it UNKNOWN;
    * a required factor of 10^0 requires nothing, because demanding an explicit multiplication by one
      would be a false alarm;
    * no factor written anywhere in the prefix is the one genuine accusation;
    * a DIFFERING factor is UNKNOWN, not a violation: the factor was written somewhere in the record and
      which numbers it was applied to is not something this checker reads. -/
def conversionAccounted (asked inCalc : Bool) (resolved : KV) (req : Option Int)
    (stated : Option Int) : OS :=
  if asked = false then OS.notRequired
  else if inCalc = false then OS.notRequired
  else match resolved with
  | KV.uu => OS.unknown
  | KV.ff => OS.unknown
  | KV.tt =>
    match req with
    | none => OS.unknown
    | some r =>
      if r = 0 then OS.notRequired
      else match stated with
        | none => OS.outstanding
        | some s => if s = r then OS.discharged else OS.unknown

/-- SOUNDNESS. A withdrawn licence - no rule, a refuted rule, a retired rule - leaves every obligation
    downstream of it UNKNOWN, for every required and stated factor.

    Every proof below is `rfl`, `cases ... <;> rfl`, or a `by_cases` chain closed by `decide`. That is
    deliberate: this file imports nothing but the Lean core, so it must not reach for a tactic that
    lives in Mathlib, and a proof that is only definitional unfolding is one a reader can check by
    unfolding the definition themselves. -/
theorem licenceWithdrawnNeverAccuses (req stated : Option Int) :
    colIdentified KV.uu = OS.unknown ∧ unitResolved KV.uu = OS.unknown ∧
    conversionAccounted true true KV.uu req stated = OS.unknown :=
  ⟨rfl, rfl, rfl⟩

/-- The normal form of the conversion rule on an UNRESOLVED scale: the required and stated factors
    cannot appear in it at all, which is what makes the next theorem true of every pair of them. -/
theorem unresolvedScaleNormalForm (asked inCalc : Bool) (req stated : Option Int) :
    conversionAccounted asked inCalc KV.uu req stated
      = (if asked = false then OS.notRequired
         else if inCalc = false then OS.notRequired else OS.unknown) := rfl

/-- An unresolved scale is NEVER reported as a missing conversion. This is the stage link: the
    obligation downstream of an unsettled interpretation abstains instead of accusing. -/
theorem unknownNeverOutstanding (asked inCalc : Bool) (req stated : Option Int) :
    conversionAccounted asked inCalc KV.uu req stated ≠ OS.outstanding := by
  rw [unresolvedScaleNormalForm]
  by_cases h : asked = false
  · rw [if_pos h]; decide
  · rw [if_neg h]
    by_cases h2 : inCalc = false
    · rw [if_pos h2]; decide
    · rw [if_neg h2]; decide

/-- THE AUDIT'S FIRST PROPERTY, as a theorem rather than as a comment. A number outside a written
    calculation is never accused, whatever else is true of it. Without this clause the obligation was
    raised for every number the actor typed, including ones it was only reading aloud: 70 of one
    attempt's 227 written numbers were reported OUTSTANDING and none survived the audit. -/
theorem outsideACalculationNeverAccuses (asked : Bool) (resolved : KV) (req stated : Option Int) :
    conversionAccounted asked false resolved req stated = OS.notRequired := by
  cases asked <;> rfl

/-- The normal form on a RESOLVED scale with both factors known. OUTSTANDING does not occur in it. -/
theorem resolvedScaleNormalForm (r s : Int) :
    conversionAccounted true true KV.tt (some r) (some s)
      = (if r = 0 then OS.notRequired else if s = r then OS.discharged else OS.unknown) := rfl

/-- THE AUDIT'S SECOND PROPERTY. A factor of ten written in the record that differs from the one this
    operand needs leaves the obligation UNSETTLED, never OUTSTANDING: the factor was written somewhere
    in the record, and which numbers it was applied to is not something this checker reads, so "the
    actor converted wrongly" is not established by the evidence it has. -/
theorem aDifferingFactorIsNeverAnAccusation (r s : Int) :
    conversionAccounted true true KV.tt (some r) (some s) ≠ OS.outstanding := by
  rw [resolvedScaleNormalForm]
  by_cases h0 : r = 0
  · rw [if_pos h0]; decide
  · rw [if_neg h0]
    by_cases h1 : s = r
    · rw [if_pos h1]; decide
    · rw [if_neg h1]; decide

/-- A rule whose CONDITION the records do not settle produces no class, in either direction. -/
theorem undeterminedWhenConditionUnknown (isIff : Bool) (cons : KV) :
    classify isIff KV.uu cons = Cls.undetermined := by
  cases isIff <;> cases cons <;> simp [classify]

/-- The same for an unsettled CONSEQUENCE. Together these two are why an incomplete record costs
    coverage and never produces a finding. -/
theorem undeterminedWhenConsequenceUnknown (isIff : Bool) (cond : KV) :
    classify isIff cond KV.uu = Cls.undetermined := by
  cases isIff <;> cases cond <;> simp [classify]

/-- An implication is not refuted by a false antecedent. -/
theorem impliesNeverCounterOnFalseCondition (cons : KV) :
    classify false KV.ff cons ≠ Cls.counter := by
  cases cons <;> simp [classify]

/-- "exactly when" is strictly stronger than "whenever": every case the biconditional refutes through
    its converse is a case the implication treats as irrelevant. -/
theorem iffIsStrictlyStronger (cons : KV) :
    classify true KV.ff cons = Cls.counterConverse → classify false KV.ff cons = Cls.neutral := by
  cases cons <;> simp [classify]

/-- An unknown conjunct can never make a conjunction true. -/
theorem unknownConjunctIsNeverTrue (a : KV) : kand KV.uu a ≠ KV.tt := by
  cases a <;> simp [kand]
"""


def _kv(v) -> str:
    return KV[v if v in (True, False) else None]


def _int(x) -> str:
    return f"({x})" if (isinstance(x, int) and x < 0) else str(int(x))


def _opt(x) -> str:
    return "none" if x is None else f"(some {_int(x)})"


def rule_rows(model: dict, ev, dom) -> list:
    """One row per scored subject, as literal values, with the class the Python side recorded."""
    rows = []
    for c in IR.active(model, "concludes"):
        is_iff = (c.get("direction") == "iff")
        for ep in ev.episodes:
            est = ev.est(ep, model["assumptions"], IR.active(model, "persists"))
            n = len(est.steps)
            ty = list((c.get("subject") or {}).values())[0]
            var = list((c.get("subject") or {}))[0]
            for ent in est.entities_of_type(n, ty):
                if K._consequence_at_end(est, c, ent, n) is None:
                    continue
                t, row = K.settle_step(c, est, var, ent, {}, dom, n)
                if row is None:
                    continue
                cond_lits = []
                for clause in c["conditions"]:
                    vals = []
                    for lit in clause:
                        r = IR.evaluate(c, [[lit]], est, t, {var: ent}, {}, dom)
                        vals.append(r["v"])
                    cond_lits.append(vals)
                rows.append({"contract": c["id"], "episode": ep["episode_id"], "subject": ent,
                             "step": t, "is_iff": is_iff, "cond": cond_lits,
                             "cons": row["cons"]["v"], "class": row["class"]})
    return rows


def obligation_rows(args, model) -> dict:
    """The distinct (licence, resolved, required, stated) tuples of each grid cell, with multiplicities.

    Distinct tuples with counts rather than one example per operand: the tuples are few, every one is
    checked, and the weighted totals are then the ablation's own headline numbers.
    """
    fz, recs, _ = RUN.load_all(args.freeze)
    uncond = None
    try:
        import oqa_fw_run as R2
        uncond = R2._unconditional(model)
    except Exception:  # noqa: BLE001
        pass
    cells = {"C_assumption_and_rule": model, "B_assumption_only": None,
             "A_no_assumption_no_rule": None, "D_assumption_and_refused_rule": uncond}
    out = {}
    for cell, m in cells.items():
        tally, totals = {}, {}
        A = () if cell == "A_no_assumption_no_rule" else model["assumptions"]
        for r in recs:
            d2 = RUN.domain_for(r, model=m)
            est = d2.estimator(r["task_type"], r["steps"], A)
            n = len(r["steps"])
            rep = ST.attempt_report(est, n, d2)
            for row in rep["operands"]:
                xref = row.get("cell")
                cell_e = (r["entities"]["cells"] or {}).get(xref) or {}
                lic = est.value(n, "col_bound", [cell_e.get("column")])["v"] if xref else None
                res = est.value(n, "cell_scale_resolved", [xref])["v"] if xref else None
                ca = row["obligations"]["conversion_accounted"]
                # EVERY INPUT THE STATE DEPENDS ON, under oqa.fw.lean.v2. The first version keyed on
                # (licence, resolved, required, stated, asked) and mapped a MISSING required factor to
                # 0 - which conflates "no factor is defined between these two scales" (UNKNOWN) with
                # "the required factor is 10^0" (NOT_REQUIRED), and left out `in_calculation`
                # altogether. A tuple that does not determine the state cannot be checked: Lean
                # faithfully disproved 24 such goals the first time this file was compiled.
                op_e = (r["entities"]["operands"] or {}).get(row["operand"]) or {}
                req = ca.get("required_exp")
                # `has_cell` is part of the tuple because the checker returns UNKNOWN for all three
                # obligations BEFORE consulting any rule when an operand matches no single data cell:
                # there is then no column to identify and no scale to resolve. Without this field that
                # case is indistinguishable from "a cell, but the question asks for no scale", whose
                # conversion obligation is NOT_REQUIRED - and the two collided in the tally, which is
                # how the first version's totals came to disagree with the report by 8.
                key = (xref is not None, lic, res, d2.asked_scale is not None,
                       bool(op_e.get("in_calculation")),
                       None if req is None else int(req), ca.get("stated_exp"))
                t = tally.setdefault(key, {"n": 0, "states": {}})
                t["n"] += 1
                for name in ST.OBLIGATIONS:
                    t["states"][name] = row["obligations"][name]["state"]
            for name, c in rep["counts"].items():
                tot = totals.setdefault(name, {})
                for st, nn in c.items():
                    tot[st] = tot.get(st, 0) + nn
        out[cell] = {"tuples": [{"has_cell": k[0], "licence": k[1], "resolved": k[2], "asked": k[3],
                                 "in_calculation": k[4], "required_exp": k[5],
                                 "stated_exp": k[6], "n": v["n"], "states": v["states"]}
                                for k, v in sorted(tally.items(), key=lambda kv: str(kv[0]))],
                     "totals": totals}
    return out


def generate(rows: list, obs: dict, model: dict) -> tuple:
    L = [PRELUDE, ""]
    L.append("-- ── the learned model's application over the real columns ─────────────────────")
    L.append(f"-- model version {model['version']}, digest {model.get('sha256', '')[:16]}")
    L.append("def rows : List Row := [")
    for i, r in enumerate(rows):
        cond = "[" + ", ".join("[" + ", ".join(_kv(v) for v in clause) + "]"
                               for clause in r["cond"]) + "]"
        L.append(f"  -- {r['episode']} @{r['step']} {r['subject']}")
        L.append(f"  ⟨{'true' if r['is_iff'] else 'false'}, {cond}, {_kv(r['cons'])}⟩"
                 + ("," if i + 1 < len(rows) else ""))
    L.append("]")
    L.append("def classes : List Cls := rows.map rowClass")
    L.append("")
    L.append("-- One statement per column: the class these definitions produce from the literal values")
    L.append("-- must be the class the Python evaluator recorded.")
    for i, r in enumerate(rows):
        L.append(f"example : rowClass (rows.getD {i} ⟨false, [], KV.uu⟩) = {CLS[r['class']]} := by decide")
    L.append("")
    L.append("-- The gate's counts, re-derived by folding over the recomputed classes.")
    for k, lean in (("support", "Cls.support"), ("counter", "Cls.counter"),
                    ("counter_converse", "Cls.counterConverse"), ("consistent", "Cls.consistent"),
                    ("undetermined", "Cls.undetermined"), ("neutral", "Cls.neutral")):
        n = sum(1 for r in rows if r["class"] == k)
        L.append(f"example : countCls {lean} classes = {n} := by decide")
    L.append("")
    L.append("-- ── the stage algebra over the exported tuples, per ablation cell ─────────────")
    L.append("structure ObRow where")
    L.append("  hasCell : Bool")
    L.append("  licence : KV")
    L.append("  resolved : KV")
    L.append("  asked : Bool")
    L.append("  inCalc : Bool")
    L.append("  req : Option Int")
    L.append("  stated : Option Int")
    L.append("  mult : Nat")
    L.append("deriving Repr")
    L.append("")
    L.append("/-- An operand matched to no single data cell has no column to identify and no scale")
    L.append("    to resolve, so all three obligations are UNKNOWN before any rule is consulted. -/")
    L.append("def obStates (r : ObRow) : OS × OS × OS :=")
    L.append("  if r.hasCell = false then (OS.unknown, OS.unknown, OS.unknown)")
    L.append("  else (colIdentified r.licence, unitResolved r.resolved,")
    L.append("        conversionAccounted r.asked r.inCalc r.resolved r.req r.stated)")
    L.append("")
    L.append("theorem unmatchedOperandNeverAccuses (l rs : KV) (a c : Bool)")
    L.append("    (q st : Option Int) (m : Nat) :")
    L.append("    obStates ⟨false, l, rs, a, c, q, st, m⟩ = (OS.unknown, OS.unknown, OS.unknown) := by")
    L.append("  simp [obStates]")
    L.append("")
    L.append("def countState (pick : ObRow → OS) (k : OS) (xs : List ObRow) : Nat :=")
    L.append("  xs.foldl (fun a r => if pick r = k then a + r.mult else a) 0")
    for cell, blk in sorted(obs.items()):
        ident = "cell" + cell.split("_")[0]
        L.append("")
        L.append(f"-- {cell}")
        L.append(f"def {ident} : List ObRow := [")
        for i, t in enumerate(blk["tuples"]):
            L.append(f"  ⟨{'true' if t['has_cell'] else 'false'}, "
                     f"{_kv(t['licence'])}, {_kv(t['resolved'])}, "
                     f"{'true' if t['asked'] else 'false'}, "
                     f"{'true' if t['in_calculation'] else 'false'}, "
                     f"{_opt(t['required_exp'])}, {_opt(t['stated_exp'])}, {t['n']}⟩"
                     + ("," if i + 1 < len(blk["tuples"]) else ""))
        L.append("]")
        for i, t in enumerate(blk["tuples"]):
            trip = (f"({OS_[t['states']['column_identified']]}, "
                    f"{OS_[t['states']['unit_resolved']]}, "
                    f"{OS_[t['states']['conversion_accounted']]})")
            L.append(f"example : obStates ({ident}.getD {i} "
                     f"⟨false, KV.uu, KV.uu, false, false, none, none, 0⟩) = {trip} := by decide")
        for name, pick in (("column_identified", "(fun r => (obStates r).1)"),
                           ("unit_resolved", "(fun r => (obStates r).2.1)"),
                           ("conversion_accounted", "(fun r => (obStates r).2.2)")):
            for st, lean in sorted(OS_.items()):
                n = (blk["totals"].get(name) or {}).get(st, 0)
                L.append(f"example : countState {pick} {lean} {ident} = {n} := by decide")
    L.append("")
    L.append("end OqaFramework")
    text = "\n".join(L) + "\n"
    side = {"n_rule_rows": len(rows),
            "rule_class_counts": {k: sum(1 for r in rows if r["class"] == k)
                                  for k in {r["class"] for r in rows}},
            "cells": {c: {"n_tuples": len(b["tuples"]), "totals": b["totals"]}
                      for c, b in obs.items()},
            "n_examples": text.count("\nexample "),
            "n_theorems": text.count("\ntheorem ")}
    side["self_check"] = self_check(rows, obs)
    return text, side


# ── an independent re-derivation of the export, in Python ─────────────────────
def _k3and(vs):
    out = True
    for v in vs:
        if v is False:
            return False
        if v is None:
            out = None
    return out


def _k3or(vs):
    out = False
    for v in vs:
        if v is True:
            return True
        if v is None:
            out = None
    return out


def self_check(rows: list, obs: dict) -> dict:
    """Re-derive every exported class and total with a SECOND, deliberately naive implementation.

    This is NOT a substitute for the compiler and nothing here is reported as a Lean result. It catches
    the one failure the compiler could not: an export that disagrees with what the checker recorded, in
    which case Lean would faithfully verify the wrong numbers.
    """
    bad = []
    for r in rows:
        cond = _k3and([_k3or(cl) for cl in r["cond"]])
        cons = r["cons"]
        if cond is None or cons is None:
            cls = "undetermined"
        elif cond and cons:
            cls = "support"
        elif cond and not cons:
            cls = "counter"
        elif (not cond) and cons:
            cls = "counter_converse" if r["is_iff"] else "neutral"
        else:
            cls = "consistent"
        if cls != r["class"]:
            bad.append({"episode": r["episode"], "subject": r["subject"],
                        "recomputed": cls, "recorded": r["class"]})
    tot_bad = []
    for cell, blk in obs.items():
        for name in ST.OBLIGATIONS:
            got = {}
            for t in blk["tuples"]:
                st = t["states"][name]
                got[st] = got.get(st, 0) + t["n"]
            want = blk["totals"].get(name) or {}
            if got != want:
                tot_bad.append({"cell": cell, "obligation": name, "from_tuples": got,
                                "from_report": want})
    # THE CHECK THAT WAS MISSING, and whose absence cost a compile. The block above only asserts that
    # the tuples' multiplicities add up to the report's totals; it never asks whether the tuple's own
    # fields DETERMINE the state recorded beside them. They did not - `in_calculation` was not
    # exported and a missing required factor was written as 0 - so the export passed this function and
    # Lean disproved 24 goals. Re-deriving each state here, from the exported fields alone and with a
    # second implementation, is the same question the compiler asks, asked before the job is submitted.
    state_bad = []
    for cell, blk in obs.items():
        for t in blk["tuples"]:
            want = t["states"]
            got = _d_states(t)
            if got != {k: want[k] for k in got}:
                state_bad.append({"cell": cell, "tuple": {k: t[k] for k in
                                  ("has_cell", "licence", "resolved", "asked", "in_calculation",
                                   "required_exp", "stated_exp")},
                                  "n": t["n"], "recomputed": got,
                                  "recorded": {k: want[k] for k in got}})
    return {"rows_checked": len(rows), "row_mismatches": bad[:8], "n_row_mismatches": len(bad),
            "total_mismatches": tot_bad[:8], "n_total_mismatches": len(tot_bad),
            "n_tuples_checked": sum(len(b["tuples"]) for b in obs.values()),
            "state_mismatches": state_bad[:8], "n_state_mismatches": len(state_bad),
            "clean": not bad and not tot_bad and not state_bad}


# The three obligation rules again, deliberately written a second time and from the EXPORTED fields
# only. If this disagrees with the checker, either the export is incomplete or one of the two
# implementations is wrong, and both are worth knowing before a compiler says so.
def _d_states(t: dict) -> dict:
    if not t["has_cell"]:
        return {"column_identified": ST.UNKNOWN, "unit_resolved": ST.UNKNOWN,
                "conversion_accounted": ST.UNKNOWN}
    return {"column_identified": _d_col(t["licence"]),
            "unit_resolved": _d_unit(t["resolved"]),
            "conversion_accounted": _d_conv(t["asked"], t["in_calculation"], t["resolved"],
                                            t["required_exp"], t["stated_exp"])}


def _d_col(licence):
    return ST.DISCHARGED if licence is True else ST.UNKNOWN


def _d_unit(resolved):
    if resolved is True:
        return ST.DISCHARGED
    return ST.UNKNOWN if resolved is None else ST.NOT_REQUIRED


def _d_conv(asked, in_calc, resolved, req, stated):
    if not asked or not in_calc:
        return ST.NOT_REQUIRED
    if resolved is not True:
        return ST.UNKNOWN
    if req is None:
        return ST.UNKNOWN
    if int(req) == 0:
        return ST.NOT_REQUIRED
    if stated is None:
        return ST.OUTSTANDING
    return ST.DISCHARGED if int(stated) == int(req) else ST.UNKNOWN


def lean_version(lean_bin: str) -> str:
    try:
        p = subprocess.run([lean_bin, "--version"], capture_output=True, text=True, timeout=60)
        return (p.stdout or p.stderr).strip().splitlines()[0] if (p.stdout or p.stderr) else "?"
    except Exception as exc:  # noqa: BLE001
        return f"unavailable: {type(exc).__name__}"


def run_lean(path: str, lean_bin: str, timeout: int = 1800) -> dict:
    if not (os.path.isfile(lean_bin) and os.access(lean_bin, os.X_OK)):
        return {"ran": False, "why": f"no executable lean at {lean_bin}"}
    try:
        p = subprocess.run([lean_bin, path], capture_output=True, text=True, timeout=timeout)
    except subprocess.TimeoutExpired:
        return {"ran": True, "returncode": -1, "why": f"timed out after {timeout}s"}
    warn = [l for l in p.stdout.splitlines() if ": warning:" in l]
    err = [l for l in p.stdout.splitlines() if ": error:" in l]
    return {"ran": True, "returncode": p.returncode, "n_warnings": len(warn), "n_errors": len(err),
            "stdout_tail": p.stdout[-4000:], "stderr_tail": p.stderr[-4000:],
            "all_statements_accepted": p.returncode == 0 and not err}


def main(argv=None) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", required=True)
    ap.add_argument("--freeze", default=RUN.FREEZE)
    ap.add_argument("--lean-bin", default=os.environ.get("LEAN_BIN", "lean"))
    a = ap.parse_args(argv)
    model = IR.load_frozen(os.path.join(a.out, "FW_MODEL.json"))
    fz, recs, _ = RUN.load_all(a.freeze)
    scored = [r for r in recs if r["role"] == "learn" and r["episode_id"] != RUN.RESERVED] + \
             [r for r in recs if r["role"] == "check" or r["episode_id"] == RUN.RESERVED]
    dom, ev = RUN.evidence_of(scored, model=model)
    rows = rule_rows(model, ev, dom)
    obs = obligation_rows(a, model)
    text, side = generate(rows, obs, model)
    path = os.path.join(a.out, "OqaFramework.lean")
    os.makedirs(a.out, exist_ok=True)
    with open(path, "w") as f:
        f.write(text)
    digest = hashlib.sha256(text.encode()).hexdigest()
    receipt = {"schema": SCHEMA, "rule": RUN.RULE,
               "source": os.path.abspath(path), "source_sha256": digest, "source_bytes": len(text),
               "model_sha256": model.get("sha256"), "sidecar": side,
               "lean_bin": a.lean_bin, "version": lean_version(a.lean_bin),
               "scope": ("the three-valued evaluation of the learned rule over the real columns, the "
                         "gate's counts, and the stage algebra with its soundness condition. NOT the "
                         "correctness of the extraction, NOT the truth of the empirical rule."),
               "compile": run_lean(path, a.lean_bin)}
    RUN.seal(receipt)
    RUN.jdump(receipt, os.path.join(a.out, "FW_LEAN.json"))
    print(f"[lean] wrote {path} ({len(text)} bytes, {side['n_examples']} examples, "
          f"{side['n_theorems']} theorems); compiled: "
          f"{receipt['compile'].get('all_statements_accepted', False)} "
          f"({receipt['compile'].get('why', receipt['compile'].get('returncode'))})")
    return 0


if __name__ == "__main__":
    sys.exit(main())
