#!/usr/bin/env python3
"""Generate and compile the Lean file for the CONNECTED contract's encoded consequences. Rule OQA-CC-1.

WHAT LEAN CHECKS HERE, and it is a short list on purpose:

  GENERAL, over the finite three-valued domain the resolution factors through (closed by `decide`,
  which is exhaustion, not a tactic that might go through):
    1. `unknownBindingNeverViolates`  if the binding is UNKNOWN or CONFLICT then the obligation is not
       VIOLATED. This is the invariant that makes a repair sound: withdrawing a binding may withdraw a
       discharge, it may never manufacture an accusation against the actor.
    2. `dischargeNeedsTheBinding`     if the obligation is DISCHARGED then the binding HOLDS. The
       contrapositive is the stage link: withdraw the binding and the witness is withdrawn.
    3. `violationNeedsAMismatch`      a VIOLATED obligation implies the used exponent differs from the
       required one, so the accusation always names an arithmetic fact.

  DEFINITIONAL (labelled MATH, not learned):
    4. `thousandsToBillions`          the required exponent for thousands -> billions is -6, and
    5. `notMinusThree`                it is not -3, which is the error the campaign's own stage layer
       found on arm C's UID0014 ("wrong by 1,000x").

  OVER THE FINITE EXPORTED EVIDENCE:
    6. one `example ... := by decide` per committed prediction, asserting that the Python side's
       recorded state really is what the Lean definitions produce from the same inputs. This checks the
       two implementations against each other over the actual records.

WHAT LEAN DOES NOT ESTABLISH. That the extraction found the right table, cell, column or operand - those
are a TRUSTED input exported from `oqa_cc_check`. That the learned applicability condition is true of the
Treasury corpus - that is empirical and the checking records are four attempts. That a reported violation
caused the item to be answered wrongly. And nothing about the actor's reasoning.

Lean 4 core only; no Mathlib. Exponents are `Int`, which has decidable equality in core.
"""
from __future__ import annotations

import argparse
import json
import os
import re
import subprocess
import sys

RULE = "OQA-CC-1"

HEADER = """/-
  OqaConnected (research; Lean 4 core only, no Mathlib). GENERATED by research/officeqa/oqa_cc_lean.py.
  Do not edit by hand: regenerate it, so the file and the Python side cannot drift apart.

  Amendment B-1. See the module docstring of oqa_cc_lean.py for what these statements do and do not
  establish. In particular the binding truth values and the exponents in the EVIDENCE section are a
  TRUSTED export of the Python extraction, not something Lean verifies.
-/
namespace OQACC

/-- Three truth values, plus an explicit conflict: the four states a binding can be in. -/
inductive BindT where
  | holds | violated | unknown | conflict
deriving DecidableEq, Repr

/-- The four states the stage obligation can be resolved to. -/
inductive ObState where
  | discharged | violated | outstanding | unknown
deriving DecidableEq, Repr

/-- The money scales, as a finite type. Their exponents are a DEFINITION, not a hypothesis. -/
inductive Scale where
  | units | thousands | millions | billions
deriving DecidableEq, Repr

def exp10 : Scale -> Int
  | .units     => 0
  | .thousands => 3
  | .millions  => 6
  | .billions  => 9

/-- MATH: the exponent that converts `frm` into `to`. -/
def requiredExp (frm to : Scale) : Int := exp10 frm - exp10 to

/-- The stage link, exactly as `oqa_cc_check.stage_link` resolves it.
    `used` is `none` when no step states a factor. -/
def resolve (b : BindT) (frm to : Scale) (used : Option Int) : ObState :=
  match b with
  | .unknown  => .unknown
  | .conflict => .unknown
  | .violated => .unknown
  | .holds =>
    match used with
    | none => .outstanding
    | some e => if e = requiredExp frm to then .discharged else .violated

/-- 1. An unknown or conflicting binding never produces an accusation against the actor. -/
theorem unknownBindingNeverViolates (b : BindT) (frm to : Scale) (used : Option Int)
    (h : b = BindT.unknown \\/ b = BindT.conflict) : resolve b frm to used != ObState.violated := by
  rcases h with h | h <;> subst h <;> simp [resolve]

/-- 2. A discharge requires the binding to hold: withdraw the binding and the witness goes with it. -/
theorem dischargeNeedsTheBinding (b : BindT) (frm to : Scale) (used : Option Int)
    (h : resolve b frm to used = ObState.discharged) : b = BindT.holds := by
  cases b <;> simp [resolve] at h <;> rfl

/-- 3. A violation always names an arithmetic fact: the used exponent differs from the required one. -/
theorem violationNeedsAMismatch (frm to : Scale) (e : Int)
    (h : resolve BindT.holds frm to (some e) = ObState.violated) : e != requiredExp frm to := by
  simp [resolve] at h
  simp [h]

/-- 4 and 5. DEFINITIONAL, labelled MATH: thousands to billions is 10^(-6), and it is not 10^(-3). -/
example : requiredExp Scale.thousands Scale.billions = -6 := by decide
example : requiredExp Scale.thousands Scale.billions != -3 := by decide
/-- The campaign's arm C UID0014 report said "wrong by 1,000x". That is this difference. -/
example : (-3 : Int) - requiredExp Scale.thousands Scale.billions = 3 := by decide

"""


def _scale(name) -> str:
    n = (name or "").lower()
    return {"units": "Scale.units", "thousands": "Scale.thousands",
            "millions": "Scale.millions", "billions": "Scale.billions"}.get(n, "")


def _bind(t) -> str:
    return {"HOLDS": "BindT.holds", "VIOLATED": "BindT.violated",
            "UNKNOWN": "BindT.unknown", "CONFLICT": "BindT.conflict"}.get(str(t), "")


def _state(s) -> str:
    return {"DISCHARGED": "ObState.discharged", "VIOLATED": "ObState.violated",
            "OUTSTANDING": "ObState.outstanding", "UNKNOWN": "ObState.unknown"}.get(str(s), "")


def generate(evidence: list, *, asked: dict) -> tuple:
    """The Lean source, and the rows that could not be encoded (reported, never silently dropped)."""
    lines = [HEADER, "/- EVIDENCE: one line per committed prediction, re-decided from the same inputs. -/"]
    used, skipped = 0, []
    for i, row in enumerate(evidence):
        b = _bind(row.get("binding"))
        st = _state(row.get("state"))
        frm = _scale((row.get("bound_scale") or ""))
        to = _scale(asked.get(str(row.get("item"))) or "")
        if not b or not st:
            skipped.append({"row": i, "why": "binding or state not in the finite domain",
                            "binding": row.get("binding"), "state": row.get("state")})
            continue
        if b == "BindT.holds" and (not frm or not to):
            skipped.append({"row": i, "why": "a holding binding needs both scales to encode",
                            "bound_scale": row.get("bound_scale"), "asked": asked.get(str(row.get("item")))})
            continue
        frm = frm or "Scale.units"
        to = to or "Scale.units"
        e = row.get("used_exp")
        used_term = "none" if e is None else f"some ({int(e)} : Int)"
        name = re.sub(r"[^A-Za-z0-9]", "_", f"ev_{row.get('item')}_{i}")
        lines.append(f"-- {row.get('item')} {row.get('trace_key')} operand {row.get('operand')!r} "
                     f"binding {row.get('binding')} -> {row.get('state')}")
        lines.append(f"example : resolve {b} {frm} {to} ({used_term}) = {st} := by decide")
        used += 1
    lines.append("")
    lines.append("end OQACC")
    return "\n".join(lines) + "\n", {"encoded": used, "skipped": skipped}


def run_lean(path: str, lean_bin: str, timeout: int = 600) -> dict:
    try:
        p = subprocess.run([lean_bin, path], capture_output=True, text=True, timeout=timeout)
        out = (p.stdout or "") + (p.stderr or "")
        return {"ran": True, "returncode": p.returncode, "output": out[-8000:],
                "errors": [ln for ln in out.splitlines() if "error" in ln.lower()][:40]}
    except FileNotFoundError:
        return {"ran": False, "why": f"no lean binary at {lean_bin}"}
    except subprocess.TimeoutExpired:
        return {"ran": False, "why": f"lean timed out after {timeout}s"}


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", required=True, help="CC_CHECK_checking.json")
    ap.add_argument("--out", required=True)
    ap.add_argument("--lean-bin", default=os.environ.get("OQA_LEAN_BIN", "lean"))
    args = ap.parse_args()

    chk = json.load(open(args.check, encoding="utf-8"))
    asked = {str(r.get("item")): r.get("asked_scale") for r in chk.get("results") or []}
    ev = []
    for r in chk.get("results") or []:
        for p in r.get("predictions") or []:
            res = p.get("resolution") or {}
            ev.append({"item": r.get("item"), "trace_key": r.get("trace_key"),
                       "operand": (p.get("operand") or {}).get("raw"),
                       "binding": (p.get("binding") or {}).get("truth"),
                       "bound_scale": (p.get("binding") or {}).get("scale"),
                       "state": res.get("state"), "used_exp": res.get("used_exp")})
    src, stats = generate(ev, asked=asked)
    os.makedirs(args.out, exist_ok=True)
    path = os.path.join(args.out, "OqaConnected.lean")
    with open(path, "w", encoding="utf-8") as f:
        f.write(src)
    res = run_lean(path, args.lean_bin)
    doc = {"rule": RULE, "lean_file": path, "lean_sha256": __import__("hashlib").sha256(
        src.encode()).hexdigest(), "evidence": stats, "lean": res,
        "checks": ["unknownBindingNeverViolates", "dischargeNeedsTheBinding",
                   "violationNeedsAMismatch", "requiredExp thousands->billions = -6",
                   "requiredExp thousands->billions != -3", "the 1,000x difference",
                   f"{stats['encoded']} evidence example(s)"],
        "not_established": ["that the extraction bound the right table, cell, column or operand",
                            "that the learned applicability condition holds of the corpus",
                            "that a reported violation caused a wrong answer"]}
    with open(os.path.join(args.out, "CC_LEAN.json"), "w", encoding="utf-8") as f:
        json.dump(doc, f, indent=1, sort_keys=True)
    print(f"rule {RULE}  wrote {path}  ({stats['encoded']} evidence example(s), "
          f"{len(stats['skipped'])} skipped)")
    if res.get("ran"):
        print(f"  lean returncode {res['returncode']}")
        for e in res["errors"][:10]:
            print(f"    {e}")
        if res["returncode"] == 0:
            print("  LEAN: all statements accepted")
    else:
        print(f"  lean did not run: {res.get('why')}")
    return 0 if (res.get("ran") and res.get("returncode") == 0) else 1


if __name__ == "__main__":
    sys.exit(main())
