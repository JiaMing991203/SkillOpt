#!/usr/bin/env python3
"""Generate and compile the Lean file for the CONNECTED contract's encoded consequences. Rule OQA-CC-2.

WHAT LEAN CHECKS HERE, and it is a short list on purpose:

  GENERAL, over the finite domain the resolution factors through:
    1. `unknownBindingNeverViolates`     if the binding is UNKNOWN or CONFLICT the obligation is not
       VIOLATED. This is the invariant that makes a repair sound: withdrawing a binding may withdraw a
       discharge, it may never manufacture an accusation against the actor.
    2. `withdrawalReopensTheObligation`  B-2: a CONFLICT resolves to REOPENED. A withdrawal is a fact
       about the evidence, not a silent "unknown", and still never an accusation.
    3. `dischargeNeedsTheBinding`        if the obligation is DISCHARGED then the binding HOLDS. The
       contrapositive is the stage link: withdraw the binding and the witness is withdrawn.
    4. `violationNeedsTheBinding`        so does an accusation.

  THE B-2 SEMANTICS, as `by decide` statements over finite or concrete arguments:
    5. an already-compatible unit requires no factor (`requiredExp billions billions = 0`), so the
       B-1 report "requires a factor of 10^0 and no step states one" was a false alarm;
    6. applying a factor to an already-compatible value IS reported;
    7. a missing factor is OUTSTANDING, never VIOLATED;
    8. a correct factor whose result never reaches a later value is OUTSTANDING, not DISCHARGED;
    9. two theorems over every conversion verdict, carry state and pair of scales, showing that neither
       a withdrawn nor an unknown binding can become an accusation. They are stated with BINDERS, not
       as quantified propositions: core Lean has no `Decidable` instance for a `forall` over a plain
       inductive type, so `by decide` cannot close that form, and the first version of this file failed
       on exactly that.

  DEFINITIONAL (labelled MATH, not learned):
   10. the required exponent for thousands -> billions is -6, it is not -3, and the difference is the
       "wrong by 1,000x" the campaign's own stage layer reported on arm C's UID0014.

  OVER THE FINITE EXPORTED EVIDENCE:
   11. one `example ... := by decide` per committed prediction, asserting that the Python side's
       recorded state really is what the Lean definitions produce from the same inputs - now including
       the conversion verdict and whether the converted value was used. This checks the two
       implementations against each other over the actual records.

WHAT LEAN DOES NOT ESTABLISH. That the extraction found the right table, cell, column or operand - those
are a TRUSTED input exported from `oqa_cc_check`. That the learned applicability condition is true of the
Treasury corpus - that is empirical and the checking records are four attempts. That a reported violation
caused the item to be answered wrongly. And nothing about the actor's reasoning.

Lean 4 core only; no Mathlib. Exponents are `Int`, which has decidable equality in core.
"""
from __future__ import annotations

import argparse
import json
import os
import subprocess
import sys

RULE = "OQA-CC-2"

HEADER = """/-
  OqaConnected (research; Lean 4 core only, no Mathlib). GENERATED by research/officeqa/oqa_cc_lean.py.
  Do not edit by hand: regenerate it, so the file and the Python side cannot drift apart.

  Amendments B-1 and B-2. See the module docstring of oqa_cc_lean.py for what these statements do and do
  not establish. In particular the binding truth values, the scales, the conversion verdict and the
  exponents in the EVIDENCE section are a TRUSTED export of the Python extraction, not something Lean
  verifies.
-/
namespace OQACC

/-- Three truth values, plus an explicit conflict: the four states a binding can be in. -/
inductive BindT where
  | holds | violated | unknown | conflict
deriving DecidableEq, Repr

/-- The states the stage obligation can be resolved to. `reopened` is new in B-2: a withdrawal puts the
    obligation back in play, which is a different fact from "we do not know". -/
inductive ObState where
  | discharged | violated | outstanding | reopened | unknown
deriving DecidableEq, Repr

/-- What the record says about the conversion the actor performed, as a finite type. -/
inductive ConvT where
  | correct | incorrect | unknownConv | noneStated
deriving DecidableEq, Repr

/-- Was the converted value actually used in a later step? Three answers, because "not recorded" is one. -/
inductive Carried where
  | yes | no | unknown
deriving DecidableEq, Repr

/-- The money scales, as a finite type. Their exponents are a DEFINITION, not a hypothesis. -/
inductive Scale where
  | units | thousands | millions | billions
deriving DecidableEq, Repr

def exp10 : Scale -> Int
  | .units     => 0
  | .thousands => 3
  | .millions  => 6
  | .billions  => 9

/-- MATH: the exponent that converts `frm` into `to`. -/
def requiredExp (frm to : Scale) : Int := exp10 frm - exp10 to

/-- The stage link, exactly as `oqa_cc_check.stage_link` resolves it after amendment B-2.
    `used` is `none` when no step states a factor. -/
def resolve (b : BindT) (frm to : Scale) (conv : ConvT) (used : Option Int)
    (carried : Carried) : ObState :=
  match b with
  | .unknown  => .unknown
  | .conflict => .reopened
  | .violated => .unknown
  | .holds =>
    if requiredExp frm to = 0 then
      -- ALREADY COMPATIBLE. No factor is required; applying one is an error.
      match used with
      | none => .discharged
      | some e => if e = 0 then .discharged else .violated
    else
      match conv with
      | .correct =>
        match carried with
        | .no => .outstanding      -- stated correctly and never carried through
        | _   => .discharged
      | .incorrect   => .violated
      | .unknownConv => .unknown
      | .noneStated  => .outstanding

/-- 1. An unknown or conflicting binding never produces an accusation against the actor. -/
theorem unknownBindingNeverViolates (b : BindT) (frm to : Scale) (conv : ConvT) (used : Option Int)
    (carried : Carried) (h : b = BindT.unknown \/ b = BindT.conflict) :
    resolve b frm to conv used carried != ObState.violated := by
  rcases h with h | h <;> subst h <;> simp [resolve]

/-- 2. B-2: a withdrawal REOPENS the obligation. It does not quietly become "unknown", and it never
    becomes an accusation - which is what the campaign's stage layer was criticised for. -/
theorem withdrawalReopensTheObligation (frm to : Scale) (conv : ConvT) (used : Option Int)
    (carried : Carried) : resolve BindT.conflict frm to conv used carried = ObState.reopened := by
  simp [resolve]

/-- 3. A discharge requires the binding to hold: withdraw the binding and the witness goes with it. -/
theorem dischargeNeedsTheBinding (b : BindT) (frm to : Scale) (conv : ConvT) (used : Option Int)
    (carried : Carried) (h : resolve b frm to conv used carried = ObState.discharged) :
    b = BindT.holds := by
  cases b <;> simp [resolve] at h <;> rfl

/-- 4. And so does an accusation: a VIOLATED obligation requires a holding binding. -/
theorem violationNeedsTheBinding (b : BindT) (frm to : Scale) (conv : ConvT) (used : Option Int)
    (carried : Carried) (h : resolve b frm to conv used carried = ObState.violated) :
    b = BindT.holds := by
  cases b <;> simp [resolve] at h <;> rfl

/- 5. The B-2 semantics, over finite arguments, closed by exhaustion. -/

/-- An already-compatible unit needs no factor: this is audit finding 6, and the false alarm the B-1
    prototype printed on UID0044 ("requires a factor of 10^0 and no step states one"). -/
example : requiredExp Scale.billions Scale.billions = 0 := by decide
example : resolve BindT.holds Scale.billions Scale.billions ConvT.noneStated none Carried.unknown
    = ObState.discharged := by decide
/-- Converting a value that was already in the asked scale IS an error, and is still reported. -/
example : resolve BindT.holds Scale.billions Scale.billions ConvT.noneStated (some (-3 : Int))
    Carried.unknown = ObState.violated := by decide
/-- A missing factor is an OUTSTANDING obligation, never an accusation. -/
example : resolve BindT.holds Scale.thousands Scale.billions ConvT.noneStated none Carried.unknown
    = ObState.outstanding := by decide
/-- A correct factor whose result never reaches a later value is not a completed conversion
    (audit finding 7). -/
example : resolve BindT.holds Scale.thousands Scale.billions ConvT.correct (some (-6 : Int))
    Carried.no = ObState.outstanding := by decide
example : resolve BindT.holds Scale.thousands Scale.billions ConvT.correct (some (-6 : Int))
    Carried.yes = ObState.discharged := by decide
/-- The campaign's arm C UID0014 shape: thousands read as millions, wrong by 10^3. -/
example : resolve BindT.holds Scale.thousands Scale.billions ConvT.incorrect (some (-3 : Int))
    Carried.yes = ObState.violated := by decide
/-- No conversion verdict, no carry state and no pair of scales can turn an unknown binding into an
    accusation. Stated with BINDERS rather than as a quantified proposition: core Lean has no
    `Decidable` instance for `forall x : MyInductive, p x` (that needs a Fintype, which lives in
    Mathlib), so `by decide` cannot close the quantified form - and a statement that cannot be checked
    is worse than no statement. The first attempt at this file failed on exactly that. -/
theorem unknownNeverAccusesWhateverTheConversion (frm to : Scale) (conv : ConvT) (used : Option Int)
    (carried : Carried) : resolve BindT.unknown frm to conv used carried != ObState.violated := by
  simp [resolve]

/-- Nor can a withdrawn one. -/
theorem withdrawalNeverAccusesWhateverTheConversion (frm to : Scale) (conv : ConvT)
    (used : Option Int) (carried : Carried) :
    resolve BindT.conflict frm to conv used carried != ObState.violated := by
  simp [resolve]

/-- An already-compatible unit requires no factor, at every money scale, by exhaustion. -/
example : requiredExp Scale.units Scale.units = 0 := by decide
example : requiredExp Scale.thousands Scale.thousands = 0 := by decide
example : requiredExp Scale.millions Scale.millions = 0 := by decide
example : resolve BindT.holds Scale.units Scale.units ConvT.noneStated none Carried.unknown
    = ObState.discharged := by decide
example : resolve BindT.holds Scale.thousands Scale.thousands ConvT.noneStated none Carried.unknown
    = ObState.discharged := by decide
example : resolve BindT.holds Scale.millions Scale.millions ConvT.noneStated none Carried.unknown
    = ObState.discharged := by decide
/-- And a withdrawal reopens, rather than silently becoming "unknown". -/
example : resolve BindT.conflict Scale.thousands Scale.billions ConvT.noneStated none Carried.unknown
    = ObState.reopened := by decide

/-- 6 and 7. DEFINITIONAL, labelled MATH: thousands to billions is 10^(-6), and it is not 10^(-3). -/
example : requiredExp Scale.thousands Scale.billions = -6 := by decide
example : requiredExp Scale.thousands Scale.billions != -3 := by decide
/-- The campaign's arm C UID0014 report said "wrong by 1,000x". That is this difference. -/
example : (-3 : Int) - requiredExp Scale.thousands Scale.billions = 3 := by decide

"""


def _scale(name) -> str:
    n = (name or "").lower()
    return {"units": "Scale.units", "thousands": "Scale.thousands",
            "millions": "Scale.millions", "billions": "Scale.billions"}.get(n, "")


def _bind(t) -> str:
    return {"HOLDS": "BindT.holds", "VIOLATED": "BindT.violated",
            "UNKNOWN": "BindT.unknown", "CONFLICT": "BindT.conflict"}.get(str(t), "")


def _state(s) -> str:
    return {"DISCHARGED": "ObState.discharged", "VIOLATED": "ObState.violated",
            "OUTSTANDING": "ObState.outstanding", "REOPENED": "ObState.reopened",
            "UNKNOWN": "ObState.unknown"}.get(str(s), "")


def _conv(v) -> str:
    return {"correct_conversion": "ConvT.correct", "correct_factor_stated": "ConvT.correct",
            "incorrect_conversion": "ConvT.incorrect",
            "incorrect_factor_stated": "ConvT.incorrect",
            "unknown_conversion": "ConvT.unknownConv",
            # `no_conversion_required` reaches the already-compatible branch, where the conversion
            # verdict is not consulted at all: the scales decide it.
            "no_conversion_required": "ConvT.noneStated",
            "no_factor_stated": "ConvT.noneStated"}.get(str(v), "ConvT.noneStated")


def _carried(v) -> str:
    if v is True:
        return "Carried.yes"
    if v is False:
        return "Carried.no"
    return "Carried.unknown"


def generate(evidence: list, *, asked: dict) -> tuple:
    """The Lean source, and the rows that could not be encoded (reported, never silently dropped)."""
    lines = [HEADER, "/- EVIDENCE: one line per committed prediction, re-decided from the same inputs. -/"]
    used, skipped = 0, []
    for i, row in enumerate(evidence):
        b = _bind(row.get("binding"))
        st = _state(row.get("state"))
        frm = _scale((row.get("bound_scale") or ""))
        to = _scale(asked.get(str(row.get("item"))) or "")
        if not b or not st:
            skipped.append({"row": i, "why": "binding or state not in the finite domain",
                            "binding": row.get("binding"), "state": row.get("state")})
            continue
        if b == "BindT.holds" and (not frm or not to):
            skipped.append({"row": i, "why": "a holding binding needs both scales to encode",
                            "bound_scale": row.get("bound_scale"), "asked": asked.get(str(row.get("item")))})
            continue
        frm = frm or "Scale.units"
        to = to or "Scale.units"
        e = row.get("used_exp")
        used_term = "none" if e is None else f"some ({int(e)} : Int)"
        cv, cr = _conv(row.get("conversion")), _carried(row.get("converted_value_used"))
        lines.append(f"-- {row.get('item')} {row.get('trace_key')} operand {row.get('operand')!r} "
                     f"binding {row.get('binding')} conv {row.get('conversion')} -> {row.get('state')}")
        lines.append(f"example : resolve {b} {frm} {to} {cv} ({used_term}) {cr} = {st} := by decide")
        used += 1
    lines.append("")
    lines.append("end OQACC")
    return "\n".join(lines) + "\n", {"encoded": used, "skipped": skipped}


def run_lean(path: str, lean_bin: str, timeout: int = 600) -> dict:
    try:
        p = subprocess.run([lean_bin, path], capture_output=True, text=True, timeout=timeout)
        out = (p.stdout or "") + (p.stderr or "")
        return {"ran": True, "returncode": p.returncode, "output": out[-8000:],
                "errors": [ln for ln in out.splitlines() if "error" in ln.lower()][:40]}
    except FileNotFoundError:
        return {"ran": False, "why": f"no lean binary at {lean_bin}"}
    except subprocess.TimeoutExpired:
        return {"ran": False, "why": f"lean timed out after {timeout}s"}


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", required=True, help="CC_CHECK_checking.json")
    ap.add_argument("--out", required=True)
    ap.add_argument("--lean-bin", default=os.environ.get("OQA_LEAN_BIN", "lean"))
    args = ap.parse_args()

    chk = json.load(open(args.check, encoding="utf-8"))
    asked = {str(r.get("item")): r.get("asked_scale") for r in chk.get("results") or []}
    ev = []
    for r in chk.get("results") or []:
        for p in r.get("predictions") or []:
            res = p.get("resolution") or {}
            if not res:
                continue        # an extraction error has no resolution to re-decide
            ev.append({"item": r.get("item"), "trace_key": r.get("trace_key"),
                       "operand": (p.get("operand") or {}).get("raw"),
                       "binding": (p.get("binding") or {}).get("truth"),
                       "bound_scale": (p.get("binding") or {}).get("scale"),
                       "conversion": (p.get("conversion") or {}).get("verdict"),
                       "converted_value_used": (p.get("conversion") or {}).get("converted_value_used"),
                       "state": res.get("state"), "used_exp": res.get("used_exp")})
    src, stats = generate(ev, asked=asked)
    os.makedirs(args.out, exist_ok=True)
    path = os.path.join(args.out, "OqaConnected.lean")
    with open(path, "w", encoding="utf-8") as f:
        f.write(src)
    res = run_lean(path, args.lean_bin)
    doc = {"rule": RULE, "lean_file": path, "lean_sha256": __import__("hashlib").sha256(
        src.encode()).hexdigest(), "evidence": stats, "lean": res,
        "checks": ["unknownBindingNeverViolates", "withdrawalReopensTheObligation",
                   "dischargeNeedsTheBinding", "violationNeedsTheBinding",
                   "requiredExp billions->billions = 0 and needs no factor",
                   "applying a factor to an already-compatible value is VIOLATED",
                   "a missing factor is OUTSTANDING, never VIOLATED",
                   "a correct factor not carried through is OUTSTANDING",
                   "unknownNeverAccusesWhateverTheConversion",
                   "withdrawalNeverAccusesWhateverTheConversion",
                   "an already-compatible unit needs no factor at every money scale",
                   "requiredExp thousands->billions = -6",
                   "requiredExp thousands->billions != -3", "the 1,000x difference",
                   f"{stats['encoded']} evidence example(s)"],
        "not_established": ["that the extraction bound the right table, cell, column or operand",
                            "that the learned applicability condition holds of the corpus",
                            "that a reported violation caused a wrong answer"]}
    with open(os.path.join(args.out, "CC_LEAN.json"), "w", encoding="utf-8") as f:
        json.dump(doc, f, indent=1, sort_keys=True)
    print(f"rule {RULE}  wrote {path}  ({stats['encoded']} evidence example(s), "
          f"{len(stats['skipped'])} skipped)")
    if res.get("ran"):
        print(f"  lean returncode {res['returncode']}")
        for e in res["errors"][:10]:
            print(f"    {e}")
        if res["returncode"] == 0:
            print("  LEAN: all statements accepted")
    else:
        print(f"  lean did not run: {res.get('why')}")
    return 0 if (res.get("ran") and res.get("returncode") == 0) else 1


if __name__ == "__main__":
    sys.exit(main())
