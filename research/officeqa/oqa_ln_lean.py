#!/usr/bin/env python3
"""Generate and COMPILE the Lean file for the learned source-to-calculation contract. Rule OQA-LN-1.

WHAT LEAN CHECKS HERE, and it is deliberately a short list.

  GENERAL, over the finite domain the stage resolution factors through:
    1. `refutationNeverAccuses`      if the learned rule was refuted on an operand, `source_traced`
       resolves to UNKNOWN - never VIOLATED and never OUTSTANDING. This is the soundness condition that
       keeps a mistake by the CHECKER from being reported as a mistake by the agent.
    2. `noChannelNeverAccuses`       if no line-numbered observation exists, the state is UNKNOWN. An
       absent observation is missing knowledge, not a discharge and not an accusation.
    3. `dischargeNeedsEverythingResolved`  DISCHARGED implies the channel was available, the rule was
       not refuted, and no operand was left unresolved. The contrapositive is the stage link: withdraw
       any one of those and the witness is withdrawn.
    4. `unknownEffectIsNotNoChange`  an action whose effect is unknown resolves to UNKNOWN, not to
       "nothing changed". Stated over `Option Bool`, so the absent case is a real case.
    5. `recoveryCanDischarge`        a committed answer supported by a consistent written calculation
       discharges `answer_traced`, whatever earlier work it replaced - and `supersededIsIrrelevant`
       says the number of replaced calculations does not enter the resolution at all.

  OVER THE FINITE EXPORTED EVIDENCE:
    6. one `example ... := by decide` per exported operand, asserting that the class the Python side
       recorded really is what these Lean definitions produce from the same inputs;
    7. one per exported stage obligation, the same way.
  Those are the two implementations checked against each other over the actual records.

WHAT COMPILING THIS DOES NOT ESTABLISH. That the extraction found the right cell, line or operand -
that is a TRUSTED input exported from `oqa_ln_check`. That the learned rule is true of the Treasury
corpus - that is empirical, measured on 48 saved attempts, and reported separately. That a reported
state caused the task outcome. No Python mirror is substituted for the compiler: if `lean` is absent,
the phase reports that it did not run.
"""
from __future__ import annotations

import argparse
import datetime
import glob
import json
import os
import subprocess
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

import oqa_cc_ir as IR  # noqa: E402
import oqa_ln_check as CK  # noqa: E402

SCHEMA = "lso.officeqa_learned_source_lean.v1"
SCOPE = ("the stage resolution algebra over the exported classes - that a refutation of the learned "
         "rule and an unavailable observation channel both resolve to UNKNOWN rather than to an "
         "accusation; that `source_traced` can NEVER be VIOLATED, so unresolved provenance is never "
         "an actor error; that an ambiguous origin is UNKNOWN and not OUTSTANDING; that a discharge "
         "requires every operand settled; that a direct lookup and arithmetic the parser cannot "
         "represent are never VIOLATED; that a fragment of a larger expression is UNKNOWN and not "
         "false; that a restatement and several candidate positions settle nothing; that a "
         "replacement needs an abandoned alternative; and that an unknown action effect is not "
         "'nothing changed'; plus one decidable example per exported operand and per exported "
         "obligation checking the Python side against these definitions")

PRELUDE = r"""-- GENERATED by research/officeqa/oqa_ln_lean.py. Rule OQA-LN-1, amendment D-1.
-- Do not edit: regenerate it. The generator records this file's digest beside the compiler's output.
namespace OqaConnected

/-- How the occurrence resolver matched a written number to the observations. -/
inductive MatchT where
  | uniquePosition : MatchT
  | severalPositions : MatchT
  | noOccurrence : MatchT
deriving DecidableEq, Repr

/-- Where an operand of the supporting calculation came from. Amendment D-3 added the last two:
    an origin that is only a RESTATEMENT settles nothing, and several candidate positions settle
    nothing either. Both used to be collapsed into stronger classes. -/
inductive OpClass where
  | sourced : OpClass
  | derivedFromEarlierWork : OpClass
  | restatementOnly : OpClass
  | mathConversionFactor : OpClass
  | takenFromTheQuestion : OpClass
  | severalPossibleOrigins : OpClass
  | unresolved : OpClass
deriving DecidableEq, Repr

/-- The obligation states. `unknown` is a real state, not an absence. -/
inductive ObState where
  | discharged : ObState
  | violated : ObState
  | outstanding : ObState
  | reopened : ObState
  | unknown : ObState
deriving DecidableEq, Repr

/-- The class of one operand. `nReal` counts earlier statements that could have produced the value
    and are not identities; `nIdent` counts those that merely restate it, such as `86,000 - 0 =
    86,000`. Numeric equality alone never reaches `sourced`, and a restatement never reaches
    `derivedFromEarlierWork`. -/
def classify (sourced : Bool) (nReal nIdent : Nat) (pow10 inQuestion several : Bool) : OpClass :=
  if sourced then OpClass.sourced
  else if nReal ≠ 0 then OpClass.derivedFromEarlierWork
  else if nIdent ≠ 0 then OpClass.restatementOnly
  else if pow10 then OpClass.mathConversionFactor
  else if inQuestion then OpClass.takenFromTheQuestion
  else if several then OpClass.severalPossibleOrigins
  else OpClass.unresolved

/-- Is this operand's origin SETTLED?  Four classes settle it; three do not. -/
def settled : OpClass → Bool
  | OpClass.sourced => true
  | OpClass.derivedFromEarlierWork => true
  | OpClass.mathConversionFactor => true
  | OpClass.takenFromTheQuestion => true
  | _ => false

/-- `source_traced`. `hasSupporting` means a written calculation yields the committed answer at all;
    `refuted` means the LEARNED rule predicted a source the resolver did not confirm; `channel`
    means at least one line-numbered observation exists; `nUnsettled` counts operands of the
    SUPPORTING calculation whose origin is not settled; `nAmbiguous` counts those unsettled BECAUSE
    the records are ambiguous rather than silent. Replaced work does not appear, by construction.

    `hasSupporting` WAS MISSING AND LEAN IS WHAT FOUND THAT. Without it this function mapped an
    attempt with no supporting calculation - no operands, so zero unsettled - to `discharged`, while
    the Python side recorded UNKNOWN, and twenty-odd exported examples failed with "decide proved
    that sourceTraced false false 0 = ObState.unknown is false". Nothing to trace is not the same as
    nothing left to trace.

    `nAmbiguous` is amendment D-3a: an ambiguous origin is UNKNOWN, not OUTSTANDING. -/
def sourceTraced (hasSupporting channel refuted : Bool) (nUnsettled nAmbiguous : Nat) : ObState :=
  if !hasSupporting then ObState.unknown
  else if refuted then ObState.unknown
  else if nUnsettled = 0 then ObState.discharged
  else if !channel then ObState.unknown
  else if nAmbiguous ≠ 0 then ObState.unknown
  else ObState.outstanding

/-- `answer_traced`. Amendments D-3b and D-5: a question that states no arithmetic requirement may
    be answered by a DIRECT LOOKUP, and an attempt containing arithmetic the parser cannot represent
    - absolute-value bars, a chained expression, a fragment of one - cannot be judged at all. Both
    used to be reported as VIOLATED with an execution diagnosis against the actor. -/
def answerTraced (committed hasSupporting needsArithmetic : Bool) (nUnrepresented : Nat) : ObState :=
  if !committed then ObState.unknown
  else if hasSupporting then ObState.discharged
  else if !needsArithmetic then ObState.unknown
  else if nUnrepresented ≠ 0 then ObState.unknown
  else ObState.violated

/-- `arith_recorded`. Amendment D-4: a fragment of a larger expression is OUT OF SCOPE, not false. -/
def arithRecorded (hasSupporting fragment consistent : Bool) : ObState :=
  if !hasSupporting then ObState.unknown
  else if fragment then ObState.unknown
  else if consistent then ObState.discharged else ObState.violated

/-- Amendment D-3e. A replacement is demonstrated only when some earlier calculation is ABANDONED -
    its result reaches the supporting calculation by no path. In a multi-step computation every
    intermediate result differs from the answer while being consumed by it, so "an earlier result
    differs from the answer" is necessary and not sufficient. -/
def replacementDemonstrated (nAbandoned : Nat) : Bool := nAbandoned ≠ 0

/-- An action's effect, where `none` means the records do not say. -/
def resolveEffect : Option Bool → ObState
  | none => ObState.unknown
  | some true => ObState.discharged
  | some false => ObState.outstanding

-- ── 1. a refutation of the learned rule is never an accusation ──────────────
theorem refutationNeverAccuses (hs ch : Bool) (n m : Nat) :
    sourceTraced hs ch true n m = ObState.unknown := by
  cases hs <;> simp [sourceTraced]

-- ── 2. missing knowledge stays unknown ─────────────────────────────────────
theorem noChannelNeverAccuses (hs rf : Bool) (n m : Nat) (h : n ≠ 0) :
    sourceTraced hs false rf n m = ObState.unknown := by
  cases hs <;> cases rf <;> simp [sourceTraced, h]

-- ── 2a. `source_traced` can NEVER be an accusation of the actor ────────────
-- Amendment D-3a. Unresolved provenance used to carry `actor_execution_diagnosis=True`, and the
-- report the paired rehearsal delivered said "actionable execution diagnoses 1" on the strength of
-- it. Missing provenance is not an actor error, in any branch.
theorem sourceTracedIsNeverViolated (hs ch rf : Bool) (n m : Nat) :
    sourceTraced hs ch rf n m ≠ ObState.violated := by
  cases hs <;> cases ch <;> cases rf <;>
    by_cases hn : n = 0 <;> by_cases hm : m = 0 <;> simp [sourceTraced, hn, hm]

-- ── 2b. nothing to trace is UNKNOWN, not a discharge ───────────────────────
theorem nothingToTraceIsUnknown (ch rf : Bool) (n m : Nat) :
    sourceTraced false ch rf n m = ObState.unknown := by
  simp [sourceTraced]

-- ── 2c. an AMBIGUOUS origin is unknown, never outstanding ──────────────────
theorem ambiguityIsUnknownNotOutstanding (n m : Nat) (hn : n ≠ 0) (hm : m ≠ 0) :
    sourceTraced true true false n m = ObState.unknown := by
  simp [sourceTraced, hn, hm]

-- ── 3. a discharge needs every part of the chain ───────────────────────────
theorem dischargeNeedsEverythingResolved (hs ch rf : Bool) (n m : Nat)
    (h : sourceTraced hs ch rf n m = ObState.discharged) : hs = true ∧ rf = false ∧ n = 0 := by
  cases hs
  · simp [sourceTraced] at h
  · cases rf
    · by_cases hn : n = 0
      · exact ⟨rfl, rfl, hn⟩
      · cases ch <;> by_cases hm : m = 0 <;> simp [sourceTraced, hn, hm] at h
    · simp [sourceTraced] at h

-- ── 4. an unknown effect is not "nothing changed" ──────────────────────────
theorem unknownEffectIsNotNoChange : resolveEffect none = ObState.unknown := by
  simp [resolveEffect]

theorem unknownEffectIsNotDischarged (e : Option Bool)
    (h : resolveEffect e = ObState.discharged) : e = some true := by
  cases e with
  | none => simp [resolveEffect] at h
  | some b => cases b <;> simp [resolveEffect] at h <;> rfl

-- ── 5. corrected work can discharge, and replaced work does not enter ──────
theorem recoveryCanDischarge (na : Bool) (k : Nat) :
    answerTraced true true na k = ObState.discharged := by
  simp [answerTraced]

/-- Replaced work cannot enter this resolution, because it is not an argument to it: `sourceTraced`
    sees only the SUPPORTING calculation's unsettled count. The first version of this file tried to
    say so with `sourceTraced ... = sourceTraced ...`, which is vacuous and which Lean flagged as an
    unused variable; the consequence that actually matters is stated instead. -/
theorem replacedWorkCanStillDischarge (ch : Bool) (m : Nat) :
    sourceTraced true ch false 0 m = ObState.discharged := by
  cases ch <;> simp [sourceTraced]

-- ── 6. the two false-accusation classes amendment D-5 withdrew ─────────────
/-- A question that needs no arithmetic may be answered by a direct lookup. -/
theorem directLookupIsNeverViolated (c : Bool) (k : Nat) :
    answerTraced c false false k = ObState.unknown := by
  cases c <;> simp [answerTraced]

/-- Arithmetic the parser cannot represent cannot be judged. -/
theorem unrepresentedArithmeticIsNeverViolated (na : Bool) (k : Nat) (h : k ≠ 0) :
    answerTraced true false na k = ObState.unknown := by
  cases na <;> simp [answerTraced, h]

/-- A VIOLATED answer requires all four conditions, so the contrapositive withdraws the accusation
    as soon as any one of them fails. -/
theorem violationNeedsEverything (c hs na : Bool) (k : Nat)
    (h : answerTraced c hs na k = ObState.violated) :
    c = true ∧ hs = false ∧ na = true ∧ k = 0 := by
  cases c
  · simp [answerTraced] at h
  · cases hs
    · cases na
      · simp [answerTraced] at h
      · by_cases hk : k = 0
        · exact ⟨rfl, rfl, rfl, hk⟩
        · simp [answerTraced, hk] at h
    · simp [answerTraced] at h

/-- A fragment of a larger expression is unknown, not false. -/
theorem fragmentIsNotFalseArithmetic (c : Bool) :
    arithRecorded true true c = ObState.unknown := by
  cases c <;> simp [arithRecorded]

-- ── 7. a restatement settles nothing ───────────────────────────────────────
theorem restatementDoesNotSettle (k : Nat) (p q sev : Bool) :
    settled (classify false 0 (k + 1) p q sev) = false := by
  simp [classify, settled]

theorem severalPositionsDoNotSettle :
    settled (classify false 0 0 false false true) = false := by
  simp [classify, settled]

-- ── 8. a replacement needs an abandoned alternative ────────────────────────
theorem consumedAncestorsAloneDoNotDemonstrateReplacement :
    replacementDemonstrated 0 = false := by
  simp [replacementDemonstrated]

-- ── a numeric match alone never reaches `sourced` ──────────────────────────
theorem uncorroboratedIsNeverSourced (nR nI : Nat) (p q sev : Bool) :
    classify false nR nI p q sev ≠ OpClass.sourced := by
  by_cases h1 : nR = 0 <;> by_cases h2 : nI = 0 <;>
    cases p <;> cases q <;> cases sev <;> simp [classify, h1, h2]
"""

_CLASS = {CK.SOURCED: "OpClass.sourced",
          CK.DERIVED: "OpClass.derivedFromEarlierWork",
          CK.RESTATEMENT_ONLY: "OpClass.restatementOnly",
          CK.MATH_FACTOR: "OpClass.mathConversionFactor",
          CK.FROM_QUESTION: "OpClass.takenFromTheQuestion",
          CK.AMBIGUOUS_ORIGIN: "OpClass.severalPossibleOrigins",
          CK.UNRESOLVED: "OpClass.unresolved"}
_STATE = {CK.DISCHARGED: "ObState.discharged", CK.VIOLATED: "ObState.violated",
          CK.OUTSTANDING: "ObState.outstanding", CK.REOPENED: "ObState.reopened",
          CK.UNKNOWN: "ObState.unknown"}


def _b(v) -> str:
    return "true" if v else "false"


def generate(stage_docs: list) -> tuple:
    """One example per exported operand and per exported obligation.

    Every input comes from the stage report's own `lean_inputs` block and its operand rows, so a
    disagreement is between the two IMPLEMENTATIONS and not between two readings of one record.
    """
    lines = [PRELUDE, "",
             "-- ── the exported evidence ──────────────────────────────────────────────────"]
    n_ops = n_obl = 0
    skipped = []
    for doc in stage_docs:
        for rep in doc["reports"]:
            li = rep.get("lean_inputs")
            if li is None:
                skipped.append({"attempt": rep["attempt_id"],
                                "why": "this stage report predates the lean_inputs block"})
                continue
            for o in rep.get("supporting_operands") or []:
                cls = _CLASS.get(o["class"])
                if not cls:
                    skipped.append({"attempt": rep["attempt_id"], "operand": o["operand"],
                                    "why": f"unmapped class {o['class']}"})
                    continue
                lines.append(
                    f"-- {rep['attempt_id']} operand {o['operand']} ({o['class']})\n"
                    f"example : classify {_b(o['sourced'])} {o.get('n_real_producers', 0)} "
                    f"{o.get('n_identity_producers', 0)} "
                    f"{_b(o['features']['round_power_of_ten'])} "
                    f"{_b(o['features']['appears_in_question'])} "
                    f"{_b(o['verdict_match'] == 'SEVERAL_POSITIONS')} = {cls} := by decide")
                lines.append(
                    f"example : settled ({cls}) = {_b(o['origin_settled'])} := by decide")
                n_ops += 2
            for o in rep["obligations"]:
                st = _STATE.get(o["state"])
                if not st:
                    continue
                name = o["obligation"]
                if name == "source_traced":
                    lines.append(
                        f"-- {rep['attempt_id']} source_traced -> {o['state']}\n"
                        f"example : sourceTraced {_b(li['has_supporting'])} "
                        f"{_b(li['channel'])} {_b(li['refuted'])} "
                        f"{li['n_unsettled']} {li['n_ambiguous']} = {st} := by decide")
                    n_obl += 1
                elif name == "answer_traced":
                    lines.append(
                        f"-- {rep['attempt_id']} answer_traced -> {o['state']}\n"
                        f"example : answerTraced {_b(li['committed'])} "
                        f"{_b(li['has_supporting'])} {_b(li['needs_arithmetic'])} "
                        f"{li['n_unrepresented']} = {st} := by decide")
                    n_obl += 1
                elif name == "arith_recorded":
                    lines.append(
                        f"-- {rep['attempt_id']} arith_recorded -> {o['state']}\n"
                        f"example : arithRecorded {_b(li['has_supporting'])} "
                        f"{_b(li['fragment'])} {_b(li['consistent'])} = {st} := by decide")
                    n_obl += 1
            lines.append(
                f"-- {rep['attempt_id']} replacement demonstrated?\n"
                f"example : replacementDemonstrated {li['n_abandoned']} = "
                f"{_b(rep.get('replacement_demonstrated'))} := by decide")
            n_obl += 1
    lines.append("")
    lines.append("end OqaConnected")
    text = "\n".join(lines) + "\n"
    return text, {"n_operand_examples": n_ops, "n_obligation_examples": n_obl, "skipped": skipped}


def lean_version(lean_bin: str) -> str:
    try:
        p = subprocess.run([lean_bin, "--version"], capture_output=True, text=True, timeout=60)
        return (p.stdout or p.stderr).strip().splitlines()[0] if (p.stdout or p.stderr) else "?"
    except Exception as exc:  # noqa: BLE001
        return f"unavailable: {type(exc).__name__}"


def run_lean(path: str, lean_bin: str, timeout: int = 900) -> dict:
    if not (os.path.isfile(lean_bin) and os.access(lean_bin, os.X_OK)):
        return {"ran": False, "why": f"no executable lean at {lean_bin}"}
    try:
        p = subprocess.run([lean_bin, path], capture_output=True, text=True, timeout=timeout)
    except subprocess.TimeoutExpired:
        return {"ran": True, "returncode": -1, "why": f"timed out after {timeout}s"}
    # The return code is what says whether every statement was accepted. The first version also
    # required stdout to be empty, so a LINTER WARNING made the receipt read
    # `all_statements_accepted: false` beside `returncode: 0` - two fields contradicting each other
    # about the same compile. Warnings are counted and kept, and they do not change the verdict.
    warnings = [l for l in p.stdout.splitlines() if ": warning:" in l]
    errors = [l for l in p.stdout.splitlines() if ": error:" in l]
    return {"ran": True, "returncode": p.returncode,
            "stdout_tail": p.stdout[-4000:], "stderr_tail": p.stderr[-4000:],
            "n_warnings": len(warnings), "warnings": warnings[:10],
            "n_errors": len(errors), "errors": errors[:10],
            "all_statements_accepted": p.returncode == 0 and not errors}


def main(argv=None) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--learn-root", required=True)
    ap.add_argument("--freeze", required=True)
    ap.add_argument("--out", required=True)
    ap.add_argument("--lean-bin", required=True)
    a = ap.parse_args(argv)
    os.makedirs(a.out, exist_ok=True)
    stage_paths = sorted(glob.glob(os.path.join(a.learn_root, "*_stage_reports.json")))
    if not stage_paths:
        print(f"no stage reports under {a.learn_root}: nothing to check", file=sys.stderr)
        return 2
    docs = []
    for p in stage_paths:
        with open(p, encoding="utf-8") as f:
            docs.append(json.load(f))
    text, counts = generate(docs)
    path = os.path.join(a.out, "OqaConnected.lean")
    with open(path, "w", encoding="utf-8") as f:
        f.write(text)
    digest = IR.sha(text)
    ver = lean_version(a.lean_bin)
    res = run_lean(path, a.lean_bin)
    receipt = {
        "schema": SCHEMA, "written_utc": datetime.datetime.now(datetime.timezone.utc).isoformat(),
        "source": os.path.abspath(path), "source_sha256": digest, "source_bytes": len(text),
        "lean_bin": a.lean_bin, "version": ver,
        "stage_reports": [{"path": p, "contract": d["contract"],
                           "contract_sha256": d["contract_sha256"],
                           "n_attempts": d["n_attempts"]} for p, d in zip(stage_paths, docs)],
        "n_examples": counts["n_operand_examples"] + counts["n_obligation_examples"],
        **counts,
        "scope": SCOPE,
        "does_not_establish": ["that the extraction found the right cell, line or operand",
                              "that the learned rule is true of the corpus",
                              "that any reported state caused the task outcome"],
        "result": res,
    }
    out = os.path.join(a.out, "LN_LEAN.json")
    with open(out, "w", encoding="utf-8") as f:
        json.dump(receipt, f, indent=1, sort_keys=True)
    print(f"lean {ver}  rc {res.get('returncode')}  examples {receipt['n_examples']}  "
          f"source {digest[:16]}")
    if res.get("stderr_tail"):
        print(res["stderr_tail"][-2000:], file=sys.stderr)
    return 0 if res.get("returncode") == 0 else 1


if __name__ == "__main__":
    raise SystemExit(main())
