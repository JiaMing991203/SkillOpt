"""Amendment A4 section 8: Lean 4 (core only) file for the connected stage-action layer + its Python mirror.

Three status classes, kept separate in the file and in every report:
  GENERAL     composition results over ALL traces (parametric): a learned effect of an observed success, plus
              persistence (no later observed command touches the literal), gives the literal's value at any later
              step; countermodels show that each premise is needed. A proof says nothing about whether a learned
              effect is TRUE of the environment: the effect is a named premise (an empirical hypothesis).
  FINITE      finite exported-trace checks of real connected chains (X2: a learned requirement's CNF evaluated on
              the exported fact values of one prefix; X3: a forecast effect literal that a learned requirement of an
              open stage needs). The export itself (parsing, fact values) is TRUSTED Python, not checked by Lean.
  EMPIRICAL   evidence counts of learned contracts are NOT in this file (they are in the earlier lean_gen bundles).
"""
from __future__ import annotations

import json
import os
import re

HEADER = """-- A4 connected stage-action layer (GENERATED by research/learned_contracts/a4_lean.py; Lean 4 core only)
set_option maxRecDepth 20000
namespace A4Conn

/-- one observed step: whether its command succeeded, and the literal values its report (or, for a learned effect,
    the effect hypothesis) sets; literals are natural numbers -/
structure Step where
  ok : Bool
  sets : List (Nat × Bool)
deriving Repr

def setsLit (s : Step) (l : Nat) : Option Bool :=
  match s.sets.find? (fun p => p.1 == l) with
  | some p => some p.2
  | none => none

def step (st : Nat → Bool) (s : Step) : Nat → Bool :=
  fun l => match setsLit s l with
    | some b => b
    | none => st l

/-- persistence semantics: a literal keeps its value until a step sets it -/
def run : (Nat → Bool) → List Step → (Nat → Bool)
  | st, [] => st
  | st, s :: rest => run (step st s) rest

-- ===================================================================== GENERAL (all traces)
theorem run_append : ∀ (pre post : List Step) (st : Nat → Bool), run st (pre ++ post) = run (run st pre) post
  | [], _, _ => rfl
  | s :: rest, post, st => by
    show run (step st s) (rest ++ post) = run (run (step st s) rest) post
    exact run_append rest post (step st s)

theorem run_untouched : ∀ (post : List Step) (st : Nat → Bool) (l : Nat),
    (∀ s' ∈ post, setsLit s' l = none) → run st post l = st l
  | [], _, _, _ => rfl
  | s' :: rest, st, l, h => by
    have h1 : setsLit s' l = none := h s' (List.Mem.head _)
    have h2 : ∀ s'' ∈ rest, setsLit s'' l = none := fun s'' hm => h s'' (List.Mem.tail _ hm)
    show run (step st s') rest l = st l
    rw [run_untouched rest (step st s') l h2]
    simp [step, h1]

/-- CONNECTION (X1 / X3 schema): the learned effect of the successful step s sets literal l to v (premise heff, an
    EMPIRICAL hypothesis), and no later observed step touches l (premise hpers, the persistence assumption); then l = v
    at the end, i.e. a later stage requirement 'l = v' is supported. -/
theorem effect_supports_requirement (init : Nat → Bool) (pre post : List Step) (s : Step) (l : Nat) (v : Bool)
    (heff : setsLit s l = some v) (hpers : ∀ s' ∈ post, setsLit s' l = none) :
    run init (pre ++ s :: post) l = v := by
  rw [run_append]
  show run (step (run init pre) s) post l = v
  rw [run_untouched post _ l hpers]
  simp [step, heff]

/-- the effect premise is needed: without it (the step sets nothing) the requirement can fail -/
theorem effect_premise_needed :
    ∃ (init : Nat → Bool) (s : Step), setsLit s 0 = none ∧ run init [s] 0 ≠ true :=
  ⟨fun _ => false, ⟨true, []⟩, by decide, by decide⟩

/-- the persistence premise is needed: a later step that sets the literal breaks the conclusion -/
theorem persistence_premise_needed :
    ∃ (init : Nat → Bool) (s s2 : Step), setsLit s 0 = some true ∧ run init [s, s2] 0 ≠ true :=
  ⟨fun _ => false, ⟨true, [(0, true)]⟩, ⟨true, [(0, false)]⟩, by decide, by decide⟩

-- ===================================================================== FINITE exported-trace checks
/-- Kleene value of a CNF (list of clauses; a clause is a list of (literal id, wanted value)) under exported
    three-valued facts (none = unknown) -/
def litVal (facts : List (Nat × Option Bool)) (q : Nat × Bool) : Option Bool :=
  match facts.find? (fun p => p.1 == q.1) with
  | some (_, some b) => some (b == q.2)
  | _ => none

def kOr : List (Option Bool) → Option Bool
  | [] => some false
  | x :: xs => match x, kOr xs with
    | some true, _ => some true
    | _, some true => some true
    | some false, some false => some false
    | _, _ => none

def kAnd : List (Option Bool) → Option Bool
  | [] => some true
  | x :: xs => match x, kAnd xs with
    | some false, _ => some false
    | _, some false => some false
    | some true, some true => some true
    | _, _ => none

def evalCNF (facts : List (Nat × Option Bool)) (cnf : List (List (Nat × Bool))) : Option Bool :=
  kAnd (cnf.map (fun c => kOr (c.map (litVal facts))))
"""


def _ob(v):
    return "none" if v is None else f"(some {'true' if v else 'false'})"


def k_or(xs):
    if any(x is True for x in xs):
        return True
    return False if all(x is False for x in xs) else None


def k_and(xs):
    if any(x is False for x in xs):
        return False
    return True if all(x is True for x in xs) else None


def generate(prep_dir: str, model: dict) -> tuple:
    """Lean text + Python mirror results for every X2 / X3-enabling connection of the Study A units"""
    import ir
    U = json.load(open(os.path.join(prep_dir, "UNITS.json")))
    lines, mirror, seen = [HEADER], [], set()
    n = 0
    for u in U["units"]:
        rep = json.load(open(os.path.join(prep_dir, "units", u["uid"], "reports.json")))
        for tid, conns in rep["connections"].items():
            for c in conns:
                if c["type"] not in ("X2",) or (tid, c["t"], c["action"]) in seen:
                    continue
                seen.add((tid, c["t"], c["action"]))
                cid = c.get("contract")
                if not cid:
                    continue
                con = next(x for x in model["contracts"] if x["id"] == cid)
                facts = dict(c["facts"])
                from vocab import parse_command
                cmd = parse_command(c["action"])
                for clause in con["condition"]:   # literals the Kleene evaluation did not need: not exported
                    for l in clause:
                        g = ir.ground_args(l, cmd["args"])
                        facts.setdefault(f"{l['atom']}({','.join(g)})", None)
                keys = sorted(facts)
                idx = {k: j for j, k in enumerate(keys)}
                cnf = []
                for clause in con["condition"]:
                    cl = []
                    for l in clause:
                        g = ir.ground_args(l, cmd["args"])
                        key = f"{l['atom']}({','.join(g)})"
                        cl.append((idx[key], bool(l["value"])))
                    cnf.append(cl)
                py = k_and([k_or([(None if facts[keys[i]] is None else facts[keys[i]] == w) for i, w in cl])
                            for cl in cnf])
                n += 1
                name = f"x2_{n}"
                fl = "[" + ", ".join(f"({idx[k]}, {_ob(facts[k])})" for k in keys) + "]"
                cl = "[" + ", ".join("[" + ", ".join(f"({i}, {'true' if w else 'false'})" for i, w in c_) + "]"
                                     for c_ in cnf) + "]"
                lines.append(f"/-- FINITE X2 {u['uid']} {tid} s{c['t']} '{c['action']}': {cid} v{con.get('version')} "
                             f"false at PRE (facts: {', '.join(f'{k}={facts[k]}' for k in keys)}) -/")
                lines.append(f"theorem {name} : evalCNF {fl} {cl} = some false := by decide")
                mirror.append({"theorem": name, "unit": u["uid"], "trajectory": tid, "t": c["t"],
                               "action": c["action"], "contract": cid, "python": py, "expected": False})
    lines.append("\nend A4Conn\n")
    names = ["run_append", "run_untouched", "effect_supports_requirement", "effect_premise_needed",
             "persistence_premise_needed"] + [m_["theorem"] for m_ in mirror]
    lines += [f"#print axioms A4Conn.{x}" for x in names]
    return "\n".join(lines) + "\n", mirror, names


def generate_from_connections(conns: list, model: dict, ns_note: str) -> tuple:
    """FINITE X2 checks from a list of {record, t, action, contract, facts} (Study C fresh records)"""
    import ir
    from vocab import parse_command
    lines, mirror = [HEADER], []
    for n, c in enumerate(conns, 1):
        con = next(x for x in model["contracts"] if x["id"] == c["contract"])
        facts = dict(c["facts"])
        cmd = parse_command(c["action"])
        for clause in con["condition"]:
            for l in clause:
                facts.setdefault(f"{l['atom']}({','.join(ir.ground_args(l, cmd['args']))})", None)
        keys = sorted(facts)
        idx = {k: j for j, k in enumerate(keys)}
        cnf = [[(idx[f"{l['atom']}({','.join(ir.ground_args(l, cmd['args']))})"], bool(l["value"])) for l in cl]
               for cl in con["condition"]]
        py = k_and([k_or([(None if facts[keys[i]] is None else facts[keys[i]] == w) for i, w in cl]) for cl in cnf])
        fl = "[" + ", ".join(f"({idx[k]}, {_ob(facts[k])})" for k in keys) + "]"
        cl_ = "[" + ", ".join("[" + ", ".join(f"({i}, {'true' if w else 'false'})" for i, w in x) + "]" for x in cnf) + "]"
        lines.append(f"/-- FINITE X2 ({ns_note}) {c['record']} s{c['t']} '{c['action']}': {c['contract']} false at PRE -/")
        lines.append(f"theorem x2_{n} : evalCNF {fl} {cl_} = some false := by decide")
        mirror.append({"theorem": f"x2_{n}", "record": c["record"], "t": c["t"], "contract": c["contract"],
                       "python": py, "expected": False})
    lines.append("\nend A4Conn\n")
    names = ["run_append", "run_untouched", "effect_supports_requirement", "effect_premise_needed",
             "persistence_premise_needed"] + [m_["theorem"] for m_ in mirror]
    lines += [f"#print axioms A4Conn.{x}" for x in names]
    return "\n".join(lines) + "\n", mirror, names


def main():
    import argparse
    import ir
    ap = argparse.ArgumentParser()
    ap.add_argument("--prepared")
    ap.add_argument("--connections", help="Study C: X2_CONNECTIONS.json from study_c_diag.py")
    ap.add_argument("--model", required=True)
    ap.add_argument("--out", required=True)
    a = ap.parse_args()
    model = ir.load_frozen(a.model)
    if a.connections:
        txt, mirror, names = generate_from_connections(json.load(open(a.connections)), model, "Study C fresh")
    else:
        txt, mirror, names = generate(a.prepared, model)
    os.makedirs(a.out, exist_ok=True)
    open(os.path.join(a.out, "A4Connected.lean"), "w").write(txt)
    bad = [m for m in mirror if m["python"] is not m["expected"]]
    json.dump({"theorems": names, "mirror": mirror, "mirror_mismatches": bad, "status": "GENERATED, NOT CHECKED"},
              open(os.path.join(a.out, "A4Connected_mirror.json"), "w"), indent=1)
    print(len(names), "theorems;", len(mirror), "finite X2 checks; mirror mismatches", len(bad))


if __name__ == "__main__":
    main()
