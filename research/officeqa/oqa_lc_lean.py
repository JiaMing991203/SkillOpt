"""Lean 4 (core only) checks for the OfficeQA learned-contract layer, plus the Python mirror that must agree.

Port of `transferred/a4_lean.py` and `transferred/lean_gen.py`, in the style of
`transferred/LearnedContracts.lean`: a `Tri` Kleene type with `DecidableEq`, everything decidable by `by decide`,
no Mathlib, no `sorry`, no `native_decide`, no axioms beyond Lean's own.

What Lean is asked to check here, and what it is NOT.

  CHECKED, generally (quantified over the finite operand model):
    1. `acceptable_f_of_unit_f`   if the unit requirement is violated then the operand is not acceptable - i.e. the
                                  unit premise is load-bearing in the composition.
    2. `unknown_not_false`        an operand whose column binding is UNKNOWN makes acceptability UNKNOWN, never
                                  false. This is amendment A4 3.1's invariant ("an unknown is never turned into a
                                  false") stated as a theorem, and it is what makes the repair sound: dropping an
                                  assumption may withdraw a discharge, it may never manufacture a violation.
    3. `reopen_is_unknown`        re-evaluating an operand whose basis was INDEX_MERGE after that basis is
                                  withdrawn yields UNKNOWN for the binding and for acceptability.
  CHECKED, over the finite exported evidence:
    4. one `example ... := by decide` per adjudicated step, asserting that the recorded Kleene atom values and the
       contract's polarity really do produce the class the Python side recorded. This checks the two
       implementations against each other over the actual evidence.

  NOT established by any of the above: that the trace extraction is correct (the atom values are a TRUSTED input
  exported from `oqa_lc_cells`), that the Treasury corpus obeys a learned hypothesis, or that a reported violation
  caused the item to be answered wrongly. Those are empirical questions and the port note keeps them separate.

Running it. There is no Lean toolchain on the workstation (`lean`, `lake` and `elan` are all absent), so this
module GENERATES the file and evaluates the Python mirror; compiling it needs a cluster CPU job. `run_lean` and
`parse_results` are kept from the ALFWorld port so that a later authorized job can use them unchanged.
"""
from __future__ import annotations

import os
import re
import subprocess
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from oqa_lc_vocab import sha  # noqa: E402

TRI = {True: ".t", False: ".f", None: ".u"}
_SCALE_EXP = {"thousands": 3, "millions": 6, "billions": 9}

HEADER = r"""/-
  OqaContracts (research; Lean 4 core only, no Mathlib). GENERATED by research/officeqa/oqa_lc_lean.py.
  Do not edit by hand: regenerate it, so the file and the Python mirror cannot drift apart.

  Every statement below is closed by `by decide` or `rfl`. The general results are stated over the finite Kleene
  domain that acceptability factors through, and are therefore closed by EXHAUSTION over that domain, not by a
  tactic script that might or might not go through. `acceptable_factors` is the `rfl` bridge from the operand
  model to that domain, so exhausting it is a complete proof of the general claim.

  See the module docstring of oqa_lc_lean.py for what these theorems do and do not establish. In particular the
  Kleene atom values in the EVIDENCE section are a trusted export of the Python trace extraction, not something
  Lean verifies.
-/
namespace OQA

inductive Tri where
  | t | f | u
deriving DecidableEq, Repr

def tnot : Tri → Tri
  | .t => .f
  | .f => .t
  | .u => .u

def tand : Tri → Tri → Tri
  | .f, _ => .f
  | _, .f => .f
  | .t, .t => .t
  | _, _ => .u

def tand3 (a b c : Tri) : Tri := tand a (tand b c)

/-- How a column binding was obtained. `unknown` is a real value, not a missing one. -/
inductive Basis where
  | flat | indexMerge | unknown
deriving DecidableEq, Repr

/-- One operand of the value chain: where its cell's column came from, whether the row's period is an asked one,
    and the base-10 exponents of the cell's scale, the asked scale and the factor the actor actually applied.
    `cellExp = none` or `askedExp = none` means no scale is stated or asked, which must stay UNKNOWN. -/
structure Operand where
  basis        : Basis
  periodAsked  : Tri
  cellExp      : Option Int
  askedExp     : Option Int
  appliedExp   : Int
deriving DecidableEq, Repr

def cellBound (o : Operand) : Tri :=
  match o.basis with
  | .flat => .t
  | .indexMerge => .t
  | .unknown => .u

/-- The binding re-evaluated after the index-merge basis has been withdrawn by a repair. -/
def cellBoundAfterDrop (o : Operand) : Tri :=
  match o.basis with
  | .flat => .t
  | .indexMerge => .u
  | .unknown => .u

/-- A value stated in 10^c units and wanted in 10^a units must be scaled by 10^(c-a):
    1,004,461 in millions (c = 6) wanted in billions (a = 9) is multiplied by 10^(6-9) = 10^-3. -/
def unitDischarged (o : Operand) : Tri :=
  match o.cellExp, o.askedExp with
  | some c, some a => if o.appliedExp = c - a then .t else .f
  | _, _ => .u

/-- Acceptability factors through three Kleene values; the general results are proved over that finite domain. -/
def acceptableOf (cb pa ud : Tri) : Tri := tand3 cb pa ud

def acceptable (o : Operand) : Tri := acceptableOf (cellBound o) o.periodAsked (unitDischarged o)

def acceptableAfterDrop (o : Operand) : Tri :=
  acceptableOf (cellBoundAfterDrop o) o.periodAsked (unitDischarged o)

theorem acceptable_factors (o : Operand) :
    acceptable o = acceptableOf (cellBound o) o.periodAsked (unitDischarged o) := rfl

theorem acceptable_after_drop_factors (o : Operand) :
    acceptableAfterDrop o = acceptableOf (cellBoundAfterDrop o) o.periodAsked (unitDischarged o) := rfl

section General
/- 1. The unit premise is load-bearing: a violated unit requirement makes the operand unacceptable, whatever the
      other two premises say. Exhausted over the nine remaining Kleene combinations. -/
example : acceptableOf .t .t .f = .f := by decide
example : acceptableOf .t .f .f = .f := by decide
example : acceptableOf .t .u .f = .f := by decide
example : acceptableOf .f .t .f = .f := by decide
example : acceptableOf .f .f .f = .f := by decide
example : acceptableOf .f .u .f = .f := by decide
example : acceptableOf .u .t .f = .f := by decide
example : acceptableOf .u .f .f = .f := by decide
example : acceptableOf .u .u .f = .f := by decide

/- 2. An UNKNOWN column binding can never discharge: acceptability is then UNKNOWN or FALSE, never TRUE. This is
      amendment A4 3.1's invariant - "an unknown is never turned into a false", and equally never into a true. -/
example : acceptableOf .u .t .t = .u := by decide
example : acceptableOf .u .t .u = .u := by decide
example : acceptableOf .u .u .t = .u := by decide
example : acceptableOf .u .u .u = .u := by decide
example : acceptableOf .u .f .t = .f := by decide
example : acceptableOf .u .f .u = .f := by decide

/- 3. Withdrawing the index-merge basis reopens the binding to UNKNOWN. -/
theorem reopen_is_unknown (o : Operand) (h : o.basis = .indexMerge) : cellBoundAfterDrop o = .u := by
  unfold cellBoundAfterDrop
  rw [h]

/- 4. ... and reopening never manufactures a violation: wherever the other two premises are not already false,
      the reopened verdict is UNKNOWN, not FALSE. Exhausted over those combinations. -/
example : acceptableOf .u .t .t = .u := by decide
example : acceptableOf .u .t .u = .u := by decide
example : acceptableOf .u .u .t = .u := by decide
example : acceptableOf .u .u .u = .u := by decide

/- 5. The unit exponent arithmetic, on the two real cases of the saved traces: millions to billions is 10^-3 and
      thousands to billions is 10^-6, so applying 10^-3 to a thousands figure is a violation. -/
example : unitDischarged { basis := .flat, periodAsked := .t, cellExp := some (6 : Int),
                           askedExp := some (9 : Int), appliedExp := (-3 : Int) } = .t := by decide
example : unitDischarged { basis := .flat, periodAsked := .t, cellExp := some (3 : Int),
                           askedExp := some (9 : Int), appliedExp := (-3 : Int) } = .f := by decide
example : unitDischarged { basis := .flat, periodAsked := .t, cellExp := some (3 : Int),
                           askedExp := some (9 : Int), appliedExp := (-6 : Int) } = .t := by decide
end General

"""

FOOTER = "\nend OQA\n"


# ── the Python mirror ───────────────────────────────────────────────────────────

def m_tand(a, b):
    if a is False or b is False:
        return False
    if a is True and b is True:
        return True
    return None


def m_tand3(a, b, c):
    return m_tand(a, m_tand(b, c))


def m_cell_bound(op: dict, after_drop: bool = False):
    if op["basis"] == "flat":
        return True
    if op["basis"] == "indexMerge":
        return None if after_drop else True
    return None


def m_unit_discharged(op: dict):
    c, a = op["cellExp"], op["askedExp"]
    if c is None or a is None:
        return None
    return op["appliedExp"] == c - a


def m_acceptable(op: dict, after_drop: bool = False):
    return m_tand3(m_cell_bound(op, after_drop), op["periodAsked"], m_unit_discharged(op))


# ── exporting the evidence ──────────────────────────────────────────────────────

def operand_row(obligation_group: dict) -> dict:
    """One operand's Lean row, from its cell_bound / period_match / unit_match obligations.

    `obligation_group` is {"cell_bound": <ob>, "period_match": <ob>, "unit_match": <ob>, "witness": <cell>}.
    Exponents come from the stated scales; `appliedExp` is log10 of the binding's own scale factor, which is the
    conversion the actor applied (see `oqa_lc_chain._unit_obligation`).
    """
    w = obligation_group.get("witness") or {}
    cell_scale = w.get("scale")
    asked = obligation_group.get("asked_scale")
    basis = {"FLAT": "flat", "INDEX_MERGE": "indexMerge"}.get(w.get("column_basis"), "unknown")
    period = {"DISCHARGED": True, "VIOLATED": False}.get(
        (obligation_group.get("period_match") or {}).get("state"), None)
    applied = obligation_group.get("applied_exp", 0)
    return {"aid": obligation_group.get("aid"), "basis": basis, "periodAsked": period,
            "cellExp": _SCALE_EXP.get(cell_scale), "askedExp": _SCALE_EXP.get(asked),
            "appliedExp": int(applied),
            "expect_acceptable": None, "expect_after_drop": None}


def _lean_operand(row: dict) -> str:
    def opt(x):
        return f"(some ({x} : Int))" if x is not None else "none"
    return (f"{{ basis := .{row['basis']}, periodAsked := {TRI[row['periodAsked']]}, "
            f"cellExp := {opt(row['cellExp'])}, askedExp := {opt(row['askedExp'])}, "
            f"appliedExp := ({row['appliedExp']} : Int) }}")


def _ident(s: str) -> str:
    return re.sub(r"[^A-Za-z0-9]", "_", str(s))


def generate(operand_rows: list, atom_rows: list) -> tuple:
    """(lean source, mirror result). Mirror disagreements are reported, never silently fixed.

    `operand_rows` are `operand_row` dicts; `atom_rows` are {"aid", "contract", "atom", "predicted", "observed",
    "class"} records of the adjudicated forecast checks.
    """
    lines = [HEADER, "section Evidence\n"]
    mirror = {"operands": [], "atoms": [], "mismatches": []}

    for row in operand_rows:
        name = f"op_{_ident(row['aid'])}"
        acc = m_acceptable(row)
        drop = m_acceptable(row, after_drop=True)
        lines.append(f"/-- {row['aid']} -/")
        lines.append(f"def {name} : Operand := {_lean_operand(row)}")
        lines.append(f"example : acceptable {name} = {TRI[acc]} := by decide")
        lines.append(f"example : acceptableAfterDrop {name} = {TRI[drop]} := by decide")
        mirror["operands"].append({"aid": row["aid"], "acceptable": acc, "after_drop": drop})
        if row.get("expect_acceptable") is not None and row["expect_acceptable"] != acc:
            mirror["mismatches"].append({"aid": row["aid"], "kind": "acceptable",
                                         "python": row["expect_acceptable"], "mirror": acc})

    lines.append("")
    for r in atom_rows:
        name = f"fc_{_ident(r['aid'])}_{_ident(r['atom'])}"
        observed, predicted = r["observed"], r["predicted"]
        if observed is None:
            cls = "unresolved"
        elif bool(observed) == bool(predicted):
            cls = "confirmed"
        else:
            cls = "violated"
        expect = {"confirmed": ".t", "violated": ".f", "unresolved": ".u"}[cls]
        polarity = "id" if predicted else "tnot"
        lines.append(f"/-- {r['aid']}: contract {r['contract']} forecasts "
                     f"{'' if predicted else 'not '}{r['atom']} -/")
        lines.append(f"def {name} : Tri := {TRI[observed]}")
        lines.append(f"example : {'' if predicted else 'tnot '}{name} = {expect} := by decide")
        mirror["atoms"].append({"aid": r["aid"], "atom": r["atom"], "class": cls, "polarity": polarity})
        if r.get("class") and r["class"] != cls:
            mirror["mismatches"].append({"aid": r["aid"], "atom": r["atom"], "kind": "forecast_class",
                                         "python": r["class"], "mirror": cls})

    lines.append("\nend Evidence")
    src = "\n".join(lines) + FOOTER
    mirror["n_theorems"] = len(operand_rows) * 2 + len(atom_rows)
    mirror["n_general_theorems"] = GENERAL
    mirror["general_mirror"] = general_mirror()
    mirror["sha256"] = sha(src)
    return src, mirror


def write(src: str, path: str) -> str:
    os.makedirs(os.path.dirname(path) or ".", exist_ok=True)
    with open(path, "w", encoding="utf-8") as f:
        f.write(src)
    return sha(src)


# ── running it (cluster only) ───────────────────────────────────────────────────

# The General section's statements, counted from the header text so the number cannot go stale.
GENERAL = len(re.findall(r"^\s*(?:example|theorem)\b", HEADER, re.M))


def general_mirror() -> dict:
    """Evaluate the General section's exhaustions in Python, so the enumeration is checked before Lean sees it."""
    tri = (True, False, None)
    unit_false = {f"acceptableOf({_n(cb)},{_n(pa)},f)": m_tand3(cb, pa, False) for cb in tri for pa in tri}
    unknown_bound = {f"acceptableOf(u,{_n(pa)},{_n(ud)})": m_tand3(None, pa, ud) for pa in tri for ud in tri}
    cases = [
        ("millions->billions applying 1e-3", m_unit_discharged(
            {"cellExp": 6, "askedExp": 9, "appliedExp": -3}), True),
        ("thousands->billions applying 1e-3", m_unit_discharged(
            {"cellExp": 3, "askedExp": 9, "appliedExp": -3}), False),
        ("thousands->billions applying 1e-6", m_unit_discharged(
            {"cellExp": 3, "askedExp": 9, "appliedExp": -6}), True),
        ("no scale asked", m_unit_discharged({"cellExp": 3, "askedExp": None, "appliedExp": 0}), None),
    ]
    return {
        "unit_false_always_false": all(v is False for v in unit_false.values()),
        "unknown_bound_never_true": all(v is not True for v in unknown_bound.values()),
        "unit_arithmetic": [{"case": c, "value": v, "expected": e, "ok": v == e} for c, v, e in cases],
        "all_ok": (all(v is False for v in unit_false.values())
                   and all(v is not True for v in unknown_bound.values())
                   and all(v == e for _, v, e in cases)),
    }


def _n(v):
    return {True: "t", False: "f", None: "u"}[v]


STD_AXIOMS = {"propext", "Classical.choice", "Quot.sound"}


def run_lean(lean_bin: str, path: str, timeout: int = 900) -> tuple:
    """(returncode, combined output). Kept from the ALFWorld port; needs a Lean toolchain, so cluster only."""
    proc = subprocess.run([lean_bin, path], capture_output=True, text=True, timeout=timeout)
    return proc.returncode, (proc.stdout or "") + (proc.stderr or "")


def parse_results(rc: int, output: str, n_theorems: int) -> dict:
    """Turn a Lean run into a verdict. An error, a `sorry` or an unexpected axiom fails the check."""
    errors = [ln for ln in output.splitlines() if re.search(r"\berror\b", ln)]
    warnings = [ln for ln in output.splitlines() if re.search(r"\bwarning\b", ln)]
    sorries = [ln for ln in output.splitlines() if "sorry" in ln or "declaration uses" in ln]
    axioms = set(re.findall(r"'([A-Za-z_.]+)'", " ".join(ln for ln in output.splitlines() if "axiom" in ln)))
    return {"returncode": rc, "ok": rc == 0 and not errors and not sorries,
            "n_theorems_expected": n_theorems, "errors": errors[:20], "warnings": warnings[:20],
            "sorries": sorries[:20], "unexpected_axioms": sorted(axioms - STD_AXIOMS)}
