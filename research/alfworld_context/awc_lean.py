#!/usr/bin/env python3
"""Generate and compile the Lean file for the context-aware stage reading. Rule AWC-1.

WHAT LEAN CHECKS, and it is deliberately a short list.

  THE THREE DECISION RULES, as Bool-valued functions of the facts the reading extracts:
    1. `inspectCurrentImpliesContext`   a discharge under the pre-revision reading (a lamp use while the
       object is held) is also a discharge under the revised one. The extension is MONOTONE on clause
       (a): connecting context never withdraws a completion the old reading recognised.
    2. `inspectNeedsTheObjectHeld`      no discharge without the requested object held. A lamp-on alone
       is never a completion.
    3. `lampElsewhereNeverDischarges`   a lamp turned on where the object was not does not discharge,
       whatever else is true. This is the `same_place` requirement as an invariant.
    4. `noLampObservedNoDischarge`      with no lamp-on observed and no coincident use, the revised
       reading is silent. An unknown is not turned into a completion.
    5. `twoContextImpliesCurrent`       clause (c) is STRICTLY STRONGER: whatever it discharges, the old
       reading discharged. So it can only withdraw a completion claim, never invent one.
    6. clause (d) likewise, by exhaustion over every temperature-event list of length at most two -
       which is what the records contain. The unrestricted statement is not proved.
    7. `twoNeedsOneReceptacleInstance`  two placements in different receptacle instances of the right
       TYPE do not discharge - the concrete witness tr:2986 (cabinet 3 and cabinet 6), as arithmetic.

  OVER THE MEASURED EVIDENCE: one `example` per changed attempt, asserting that the direction the
  Python side recorded is the direction these definitions give. That checks the two implementations
  against each other on the real rows rather than on a fixture.

WHAT LEAN DOES NOT ESTABLISH. That the reading extracted the right object, receptacle or lamp from the
observation text - that is a TRUSTED input, produced by the frozen `vocab` grammar and
`stage_common.Reading`, and three of this study's own findings are about that layer. That `lamp_stays_on`
is true of ALFWorld - it is an empirical claim about the command set, stated and justified in the
amendment, not proved here. That the revised reading matches the engine's success condition - the
evidence for that is 736 saved attempts, not a proof.

Core Lean 4.20.0 only. Statements over Bool use explicit case analysis rather than a `forall` decision
procedure, because core Lean has no `Decidable` instance for a quantified proposition over a plain
inductive type - the lesson recorded in the OfficeQA connected-contract work.

usage:
  awc_lean.py --compare <AWC_COMPARE.json> --out <dir> [--lean-bin <path>]
"""
from __future__ import annotations

import argparse
import datetime
import json
import os
import subprocess
import sys

RULE = "AWC-1"

HEADER = r"""-- Generated by research/alfworld_context/awc_lean.py (rule AWC-1). Core Lean 4.20.0, no Mathlib.
-- The context-aware stage reading of ALFWorld records: the three revised clauses as decision rules,
-- their invariants, and one example per measured change.
--
-- TRUSTED INPUTS, not proved here: that the observation grammar extracted the right object, receptacle
-- and lamp; that `lamp_stays_on` holds of ALFWorld's command set; that the reading matches the engine.

namespace AwcContext

/-! ## 1. Examine in Light: the pre-revision rule and the revision -/

-- The facts the reading extracts from the prefix, as Bools:
--   held          the requested-type instance is held now
--   coincident    a lamp of the named type was used WHILE that instance was held   (clause a)
--   lampOn        a lamp of the named type was turned on earlier, with no recorded switch-off
--   samePlace     at that lamp-on the actor's arrival was the receptacle the instance was picked up at,
--                 with no arrival elsewhere in between                              (clause b)

def inspectCurrent (held coincident : Bool) : Bool := held && coincident

def inspectContext (held coincident lampOn samePlace : Bool) : Bool :=
  held && (coincident || (lampOn && samePlace))

theorem inspectCurrentImpliesContext (held coincident lampOn samePlace : Bool) :
    inspectCurrent held coincident = true →
    inspectContext held coincident lampOn samePlace = true := by
  cases held <;> cases coincident <;> cases lampOn <;> cases samePlace <;>
    simp [inspectCurrent, inspectContext]

theorem inspectNeedsTheObjectHeld (coincident lampOn samePlace : Bool) :
    inspectContext false coincident lampOn samePlace = false := by
  simp [inspectContext]

theorem lampElsewhereNeverDischarges (held lampOn : Bool) :
    inspectContext held false lampOn false = false := by
  cases held <;> cases lampOn <;> simp [inspectContext]

theorem noLampObservedNoDischarge (held samePlace : Bool) :
    inspectContext held false false samePlace = false := by
  cases held <;> cases samePlace <;> simp [inspectContext]

-- The counterexample amendment A4 3.4 was built from: lamp on at the dresser the object was picked up
-- at, object not held at the time, picked up afterwards at that same arrival.
example : inspectCurrent true false = false := by decide
example : inspectContext true false true true = true := by decide

/-! ## 2. Pick Two & Place: one receptacle INSTANCE, not one receptacle TYPE -/

-- `placed r1 r2` are the destination-receptacle instance ids of the two supported placements; both are
-- already known to be of the requested destination TYPE.

def twoCurrent (n : Nat) : Bool := n >= 2          -- two supported placements of the requested type

def twoContext (r1 r2 : Nat) : Bool := r1 == r2    -- clause (c): the same receptacle instance

theorem twoContextImpliesCurrent (r1 r2 : Nat) :
    twoContext r1 r2 = true → twoCurrent 2 = true := by
  intro _; simp [twoCurrent]

theorem twoNeedsOneReceptacleInstance (r1 r2 : Nat) (h : r1 ≠ r2) : twoContext r1 r2 = false := by
  simpa [twoContext] using h

-- The witness: cup 1 in cabinet 3 and cup 4 in cabinet 6, on an episode that scored 0.
example : twoCurrent 2 = true := by decide
example : twoContext 3 6 = false := by decide
example : twoContext 3 3 = true := by decide

/-! ## 3. Heat / Cool: the requested transformation must be the LATEST temperature event -/

inductive Temp where
  | heat : Temp
  | cool : Temp
  deriving DecidableEq

-- `events` is the list of temperature events of that instance before its placement, in order.
def heatCurrent (events : List Temp) (want : Temp) : Bool := events.contains want

def latest : List Temp -> Option Temp
  | [] => none
  | [e] => some e
  | _ :: rest => latest rest

def heatContext (events : List Temp) (want : Temp) : Bool :=
  match latest events with
  | none => false
  | some e => e == want

theorem heatContextEmptyIsSilent (want : Temp) : heatContext [] want = false := by
  rfl

-- CLAUSE (d) IS STRICTLY STRONGER, established by exhaustion over every event list of length at most
-- two, which is what the records contain (the most temperature events observed on one instance before
-- its placement is two). The unrestricted statement over arbitrary lists is NOT proved here, and this
-- comment is the limit rather than a footnote elsewhere.
example : heatContext [] Temp.heat = false := by decide
example : (heatContext [Temp.heat] Temp.heat && !heatCurrent [Temp.heat] Temp.heat) = false := by decide
example : (heatContext [Temp.cool] Temp.heat && !heatCurrent [Temp.cool] Temp.heat) = false := by decide
example : (heatContext [Temp.heat, Temp.heat] Temp.heat
            && !heatCurrent [Temp.heat, Temp.heat] Temp.heat) = false := by decide
example : (heatContext [Temp.heat, Temp.cool] Temp.heat
            && !heatCurrent [Temp.heat, Temp.cool] Temp.heat) = false := by decide
example : (heatContext [Temp.cool, Temp.heat] Temp.heat
            && !heatCurrent [Temp.cool, Temp.heat] Temp.heat) = false := by decide
example : (heatContext [Temp.cool, Temp.cool] Temp.heat
            && !heatCurrent [Temp.cool, Temp.cool] Temp.heat) = false := by decide

-- The witness: heat, then cool, then placed (counterexample tr:2658); and the repaired order.
example : heatCurrent [Temp.heat, Temp.cool] Temp.heat = true := by decide
example : heatContext [Temp.heat, Temp.cool] Temp.heat = false := by decide
example : heatContext [Temp.cool, Temp.heat] Temp.heat = true := by decide

/-! ## 4. The direction of every measured change -/

-- `Direction` is what the comparison recorded for one changed attempt. STRICTER means the context
-- reading withdrew or delayed a completion claim; LOOSER means it added one.
inductive Direction where
  | stricter : Direction
  | looser : Direction
  deriving DecidableEq

def directionOf (currentReached contextReached : Bool) (currentStep contextStep : Nat) : Direction :=
  if currentReached && !contextReached then Direction.stricter
  else if !currentReached && contextReached then Direction.looser
  else if contextStep > currentStep then Direction.stricter
  else Direction.looser

-- An extension that only ever withdraws or delays cannot manufacture a completion claim.
theorem strictOnlyWithdraws (cs xs : Nat) :
    directionOf true false cs xs = Direction.stricter := by
  simp [directionOf]

"""

FOOTER = """
end AwcContext
"""


def _utc() -> str:
    return datetime.datetime.now(datetime.timezone.utc).isoformat()


def evidence_lines(compare: dict) -> tuple:
    """One `example` per measured change, de-duplicated by (id, run, step)."""
    seen, lines, encoded, skipped = set(), [], 0, []
    rows = (compare.get("changes") or []) + (compare.get("supplementary_scan_changes") or [])
    for ch in rows:
        w, src = ch["witness"], ch.get("source") or {}
        key = (str(w.get("id")), src.get("run"), src.get("step"), src.get("role"))
        if key in seen:
            continue
        seen.add(key)
        cs, xs = w.get("current_goal_step"), w.get("context_goal_step")
        cr, xr = bool(w.get("current_reached_at_end")), bool(w.get("context_reached_at_end"))
        if (cs is None) != (not cr) or (xs is None) != (not xr):
            skipped.append({"id": w.get("id"), "why": "reached/step disagree in the record"})
            continue
        want = "Direction.looser" if (not cr and xr) else "Direction.stricter"
        lines.append(
            f"-- {w.get('id')} {src.get('role','')} hard={w.get('scored_hard')} "
            f"current@{cs} context@{xs} : {ch['classification']}\n"
            f"example : directionOf {str(cr).lower()} {str(xr).lower()} "
            f"{cs if cs is not None else 0} {xs if xs is not None else 0} = {want} := by decide")
        encoded += 1
    return lines, encoded, skipped


def run_lean(path: str, lean_bin: str, timeout: int = 600) -> dict:
    try:
        p = subprocess.run([lean_bin, path], capture_output=True, text=True, timeout=timeout)
        out = (p.stdout or "") + (p.stderr or "")
        return {"ran": True, "returncode": p.returncode, "output": out[-8000:],
                "errors": [l for l in out.splitlines() if "error" in l.lower()][:40]}
    except FileNotFoundError:
        return {"ran": False, "why": f"no lean binary at {lean_bin}"}
    except subprocess.TimeoutExpired:
        return {"ran": False, "why": f"lean timed out after {timeout}s"}


CHECKS = ["inspectCurrentImpliesContext", "inspectNeedsTheObjectHeld", "lampElsewhereNeverDischarges",
          "noLampObservedNoDischarge", "twoContextImpliesCurrent", "twoNeedsOneReceptacleInstance",
          "heatContextEmptyIsSilent",
          "clause (d) stricter, by exhaustion over event lists of length <= 2 (7 cases)",
          "strictOnlyWithdraws",
          "the lamp counterexample as two decide examples",
          "cabinet 3 vs cabinet 6 as arithmetic",
          "heat-then-cool superseded, cool-then-heat not"]


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--compare", required=True)
    ap.add_argument("--out", required=True)
    ap.add_argument("--lean-bin", default=os.environ.get("AWC_LEAN_BIN", "lean"))
    a = ap.parse_args(argv)

    cmp_doc = json.load(open(a.compare, encoding="utf-8"))
    lines, encoded, skipped = evidence_lines(cmp_doc)
    body = HEADER + "\n".join(lines) + "\n" + FOOTER
    os.makedirs(a.out, exist_ok=True)
    path = os.path.join(a.out, "AwcContext.lean")
    with open(path, "w", encoding="utf-8") as f:
        f.write(body)
    res = run_lean(path, a.lean_bin)
    doc = {"rule": RULE, "utc": _utc(), "lean_file": path,
           "checks": CHECKS + [f"{encoded} evidence example(s)"],
           "evidence": {"encoded": encoded, "skipped": skipped},
           "lean": res,
           "what_lean_does_not_establish": [
               "that the observation grammar extracted the right object, receptacle or lamp",
               "that `lamp_stays_on` is true of ALFWorld's command set (empirical, stated in A4 3.4)",
               "that the revised reading matches the engine's success condition (736 saved attempts "
               "are the evidence, not a proof)"],
           }
    out = os.path.join(a.out, "AWC_LEAN.json")
    with open(out, "w", encoding="utf-8") as f:
        json.dump(doc, f, indent=1, sort_keys=True, default=str)
    print(f"rule {RULE}  wrote {path}  ({encoded} evidence example(s), {len(skipped)} skipped)")
    if res.get("ran"):
        print(f"  lean returncode {res['returncode']}")
        for l in res["errors"]:
            print(f"    {l}")
        if res["returncode"] == 0:
            print("  LEAN: all statements accepted")
    else:
        print(f"  lean did NOT run: {res.get('why')}")
    print(f"wrote {out}")
    return 0 if (res.get("ran") and res.get("returncode") == 0) else 1


if __name__ == "__main__":
    sys.exit(main())
